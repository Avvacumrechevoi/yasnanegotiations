/* ═══════════════════════════════════════════════════════════════════════════
   СВЯЗЬ С СЕРВЕРОМ — один транспорт на всё приложение.

   ЗАЧЕМ. К серверу ходили пять разных мест, и каждое со своим порядком: у
   проверки обновлений был срок, у входа — свой, у друзей и заявок не было
   ничего. Отсюда 05.09.2026 и вышло то, что человек увидел на экране: шлюз
   перестал отвечать, а приложение не сказало об этом внятно, зато каждое
   открытие раздела уходило в мёртвый адрес и висело там, пока телефон сам не
   оборвёт соединение. Пять политик — это отсутствие политики.

   ЧТО ЗДЕСЬ ЕСТЬ (то, что принято и без чего в проде нельзя):
     • СРОК у каждого запроса. Без него запрос не падает — он висит, и экран
       навсегда остаётся со словом «Загружаю…».
     • ПОВТОРЫ с расступающейся паузой и разбросом — но ТОЛЬКО для чтения.
       Повторить POST — значит завести вторую заявку; такого мы не делаем.
     • ПРЕДОХРАНИТЕЛЬ. После трёх сбоев подряд перестаём ходить в сеть на
       полминуты и отвечаем сразу. Иначе каждый заход на экран стоит человеку
       трёх повторов по двенадцать секунд — приложение выглядит подвисшим,
       а серверу это ничем не помогает.
     • ПРИЧИНА СЛОВАМИ, а не «не получилось»: нет сети у телефона, сервер не
       отвечает, сервер отказал (и что именно он сказал).

   ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО. Повторов у записи (см. выше) и молчаливых ошибок:
   каждый отказ возвращается наружу с причиной, экран сам решает, что сказать.

   ПОЧЕМУ РАСТУЩАЯ ПАУЗА С РАЗБРОСОМ. Когда сервер вернётся, в него разом
   постучатся все, кто ждал. Ровные паузы у всех телефонов дают волну; разброс
   её размазывает. Это дешёвая вежливость к своему же серверу.

   ЗАПАСНЫЕ АДРЕСА. Список ЗАПАСНЫЕ пуст: сейчас вход в сервер один — шлюз.
   Когда появится второй (прямые адреса функций), достаточно дописать его
   сюда: транспорт перебирает адреса по очереди, а предохранитель считает
   каждый отдельно.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var СРОК = 12000;              /* мс на один запрос */
  var ПОВТОРОВ = 2;              /* сверх первой попытки, только для чтения */
  var ПАУЗЫ = [400, 1200];       /* расступающаяся пауза, к ней разброс */
  var ПОРОГ = 3;                 /* сбоев подряд до размыкания */
  var ОСТЫВАНИЕ = 30000;         /* мс, пока не ходим в сеть вовсе */

  var ПРИЧИНЫ = {
    НЕТ_АДРЕСА: 'нет-адреса',
    НЕТ_СЕТИ: 'нет-сети',
    НЕ_ОТВЕЧАЕТ: 'не-отвечает',
    ОТКАЗ: 'отказ',
  };

  /* Запасные входы в сервер. Пусто — значит вход один. */
  var ЗАПАСНЫЕ = [];

  function основной() {
    try {
      var м = document.querySelector('meta[name="yasna:api"]');
      return (м && м.getAttribute('content')) || '';
    } catch (e) { return ''; }
  }
  function адреса() {
    var с = [];
    var о = основной();
    if (о) с.push(о);
    for (var i = 0; i < ЗАПАСНЫЕ.length; i++)
      if (ЗАПАСНЫЕ[i] && с.indexOf(ЗАПАСНЫЕ[i]) < 0) с.push(ЗАПАСНЫЕ[i]);
    return с;
  }

  /* ─── Предохранитель ──────────────────────────────────────────────────
     Считаем по каждому адресу отдельно: один вход может лежать, другой
     работать. «Полуоткрыт» — пропускаем ОДИН пробный запрос; ответил —
     размыкание снимаем, снова не ответил — ждём ещё столько же. */
  var счёт = {};
  function узел(а) {
    if (!счёт[а]) счёт[а] = { подряд: 0, доКогда: 0, пробуем: false };
    return счёт[а];
  }
  function разомкнут(а) {
    var у = узел(а);
    if (Date.now() >= у.доКогда) {
      if (у.доКогда && !у.пробуем) { у.пробуем = true; return false; }  /* пробный */
      return false;
    }
    return true;
  }
  function удалось(а) { счёт[а] = { подряд: 0, доКогда: 0, пробуем: false }; }
  function сорвалось(а) {
    var у = узел(а);
    у.подряд += 1;
    у.пробуем = false;
    if (у.подряд >= ПОРОГ) у.доКогда = Date.now() + ОСТЫВАНИЕ;
  }
  /* Сеть вернулась — предохранитель ни при чём, пробуем сразу. */
  try {
    window.addEventListener('online', function () { счёт = {}; });
  } catch (e) {}

  function беда(причина, текст, доп) {
    var e = new Error(текст);
    e.причина = причина;
    if (доп) { e.код = доп.код; e.detail = доп.detail; }
    return e;
  }

  function шапка(свои) {
    var ш = { 'Content-Type': 'application/json' };
    try {
      var т = localStorage.getItem('yasna_duel_token');
      if (т) ш.Authorization = 'Bearer ' + т;
    } catch (e) {}
    try {
      if (window.YasnaStorage && window.YasnaStorage.deviceSecret)
        ш['X-Device-Secret'] = window.YasnaStorage.deviceSecret();
    } catch (e) {}
    if (свои) for (var к in свои) if (свои.hasOwnProperty(к)) ш[к] = свои[к];
    return ш;
  }

  function пауза(мс) { return new Promise(function (r) { setTimeout(r, мс); }); }
  function сРазбросом(мс) { return Math.round(мс * (0.75 + Math.random() * 0.5)); }

  /* ─── Одна попытка к одному адресу ────────────────────────────────────
     Нативный запрос (CapacitorHttp) оборвать нельзя — у него нет отмены.
     Поэтому срок ставим гонкой: ответ, пришедший после срока, просто некому
     будет принять. Для fetch пользуемся настоящей отменой. */
  function попытка(база, путь, как, тело, свояШапка, срок) {
    var url = база + путь;
    var П = (window.Capacitor && window.Capacitor.Plugins) || {};
    var разбор = function (статус, данные) {
      var д = данные;
      /* Мусор вместо JSON при успешном коде — это сбой сервера, а не пустой
         ответ: молчаливое «{}» стирало кэш ленты (ревью 8.8, F10). Пустое
         тело оставляем пустым объектом: так отвечают ручки без содержания. */
      if (typeof д === 'string') {
        var сырое = д.trim();
        if (!сырое) д = {};
        else { try { д = JSON.parse(сырое); }
               catch (e) { throw беда(ПРИЧИНЫ.ОТКАЗ, 'сервер ответил не JSON', { код: статус }); } }
      }
      д = д || {};
      if (статус >= 400)
        throw беда(ПРИЧИНЫ.ОТКАЗ, д.detail || д.error || ('код ' + статус),
                   { код: статус, detail: д.detail });
      return д;
    };

    var дело;
    if (П.CapacitorHttp) {
      дело = (как === 'GET'
        ? П.CapacitorHttp.get({ url: url, headers: свояШапка })
        : П.CapacitorHttp.request({ url: url, method: как, headers: свояШапка, data: тело || {} })
      ).then(function (r) { return разбор(r.status, r.data); });
    } else {
      var стоп = null;
      try { стоп = new AbortController(); } catch (e) {}
      дело = fetch(url, {
        method: как, headers: свояШапка,
        body: (как === 'GET' || тело == null) ? undefined : JSON.stringify(тело),
        signal: стоп ? стоп.signal : undefined,
      }).then(function (r) {
        return r.json().catch(function () { return {}; })
          .then(function (д) { return разбор(r.status, д); });
      });
      setTimeout(function () { try { стоп && стоп.abort(); } catch (e) {} }, срок);
    }

    var часы = new Promise(function (_, нет) {
      setTimeout(function () {
        нет(беда(ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ, 'сервер не ответил за ' + Math.round(срок / 1000) + ' с'));
      }, срок);
    });
    return Promise.race([дело, часы]);
  }

  /* Сбой сети от отказа сервера отличаем по причине: отказ пришёл ОТ сервера,
     значит он жив, и предохранитель его не касается. */
  function этоСеть(e) {
    if (!e) return true;
    if (e.причина === ПРИЧИНЫ.ОТКАЗ) return false;
    if (e.причина === ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ) return true;
    var т = String(e.message || '');
    return /failed to (fetch|connect)|networkerror|load failed|abort|unable to resolve|connection (refused|reset)|timeout/i.test(т);
  }

  /* ─── Зов ─────────────────────────────────────────────────────────────
     о = { как:'GET'|'POST'|'PUT', тело, срок, повторы, шапка } */
  function зов(путь, о) {
    о = о || {};
    var как = (о.как || 'GET').toUpperCase();
    var срок = о.срок || СРОК;
    /* Повторяем только чтение: повторённая запись создаёт второе обращение. */
    var повторов = (как === 'GET') ? (о.повторы == null ? ПОВТОРОВ : о.повторы) : 0;
    var сп = адреса();
    if (!сп.length)
      return Promise.reject(беда(ПРИЧИНЫ.НЕТ_АДРЕСА, 'на этой странице не задан адрес сервера'));
    try {
      if (navigator.onLine === false)
        return Promise.reject(беда(ПРИЧИНЫ.НЕТ_СЕТИ, 'нет сети'));
    } catch (e) {}

    var ш = шапка(о.шапка);
    var последняя = null;

    function поАдресам(i) {
      if (i >= сп.length) {
        return Promise.reject(последняя ||
          беда(ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ, 'сервер не отвечает'));
      }
      var база = сп[i];
      if (разомкнут(база)) {
        последняя = беда(ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ, 'сервер не отвечает');
        return поАдресам(i + 1);
      }
      function попытки(n) {
        return попытка(база, путь, как, о.тело, ш, срок).then(function (д) {
          удалось(база);
          return д;
        }).catch(function (e) {
          if (!этоСеть(e)) { удалось(база); throw e; }   /* сервер жив, но отказал */
          сорвалось(база);
          /* НАРУЖУ ВСЕГДА УХОДИТ ПРИЧИНА. Сырой TypeError('Failed to fetch')
             от браузера её не несёт, и экран, спросив e.причина, получал
             undefined и писал свою догадку вместо правды. Ради этого
             транспорт и заводился — одно место, которое знает, что случилось. */
          последняя = (e && e.причина) ? e
            : беда(ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ, 'сервер не отвечает');
          if (n < повторов) return пауза(сРазбросом(ПАУЗЫ[n] || 1200)).then(function () { return попытки(n + 1); });
          return поАдресам(i + 1);
        });
      }
      return попытки(0);
    }
    return поАдресам(0);
  }

  /* Что сказать человеку. Экран может взять готовую строку или написать свою
     по причине — но выдумывать «не получилось» больше не нужно. */
  function словами(e) {
    if (!e) return 'Не получилось.';
    switch (e.причина) {
      case ПРИЧИНЫ.НЕТ_АДРЕСА: return 'Эта страница не знает адреса сервера.';
      case ПРИЧИНЫ.НЕТ_СЕТИ:   return 'Нет сети — попробуем, когда она вернётся.';
      case ПРИЧИНЫ.НЕ_ОТВЕЧАЕТ:return 'Сервер не отвечает — попробуем позже сами.';
      case ПРИЧИНЫ.ОТКАЗ:      return e.message || 'Сервер отказал.';
      default:                 return e.message || 'Не получилось.';
    }
  }

  window.YasnaSvyaz = {
    зов: зов,
    словами: словами,
    ПРИЧИНЫ: ПРИЧИНЫ,
    /* Для проверок и экранов: жив ли вход и когда снова попробуем. */
    состояние: function () {
      var из = {};
      адреса().forEach(function (а) {
        var у = узел(а);
        из[а] = { подряд: у.подряд, разомкнут: Date.now() < у.доКогда,
                  доКогда: у.доКогда };
      });
      return из;
    },
    /* Только для стенда: сбросить предохранитель. */
    забыть: function () { счёт = {}; },
  };
})();
