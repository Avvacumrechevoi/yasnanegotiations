/* ═══════════════════════════════════════════════════════════════════════
   ЗНАНИЕ — что человек уже прошёл, собранное из всех ключей разом.

   ЗАЧЕМ. Прогресс лежал в пяти независимых ключах, и ни один экран не мог
   ответить на простой вопрос «где я остановился»: уроки считались в одном
   ключе, переговоры в другом, раскладки в третьем, а разборы не считались
   вовсе. Из-за двух несогласованных счётчиков на экране уже случалось
   «пройдено 6 из 4».

   ЧТО ЗДЕСЬ. Чтение всех источников в одну таблицу «узел → состояние» и
   запись одного собственного ключа для того, чего никто не писал: разборы.

   ПЯТЬ СОСТОЯНИЙ, И НИ ОДНОГО ЗАМКА:
     нет      — ещё не открывали
     начато   — открыли и вышли
     пройдено — дошли до конца
     держится — вернулись позже и подтвердили (ставится только играми)
     пишется  — материала ещё нет; это про нас, а не про человека

   Слово «пройдено» для уроков сегодня означает «дошли до конца»: движок
   уроков засчитывает шаг независимо от правильности ответа. Пока это так,
   на экране пишем именно «дошли до конца», а не «пройдено».

   Экспорт: window.YasnaZnanie.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
'use strict';

var КЛЮЧ = 'yasna_znanie_v1';   /* наш: разборы, открытия, даты */

function читать(ключ, поумолчанию) {
  try {
    var с = localStorage.getItem(ключ);
    if (с == null) return поумолчанию;
    return JSON.parse(с);
  } catch (e) { return поумолчанию; }
}
function строка(ключ) {
  try { return localStorage.getItem(ключ); } catch (e) { return null; }
}

function своё() { return читать(КЛЮЧ, {}) || {}; }

function записать(id, поле) {
  try {
    var д = своё();
    д[id] = Object.assign({}, д[id], поле, { когда: Date.now() });
    localStorage.setItem(КЛЮЧ, JSON.stringify(д));
  } catch (e) {}
}

/* ─── Сбор из чужих ключей ─────────────────────────────────────────── */

function пройденныеУроки() {
  var с = читать('yasna_completed_lessons_v1', []);
  return Array.isArray(с) ? с : [];
}

function раскладки() {
  /* games/krug пишет свой ключ; берём мягко — формат может меняться. */
  var д = читать('yasna_krug_v1', null);
  var итог = {};
  if (д && typeof д === 'object') {
    Object.keys(д).forEach(function (k) {
      var з = д[k];
      var верно = (з && (з.лучшее || з.best || з.верно)) || 0;
      итог[k] = { играл: true, верно: верно };
    });
  }
  return итог;
}

function переговоры() {
  var с = читать('yasna_neg_lessons_v1', []);
  return Array.isArray(с) ? с.length : 0;
}

function свои() {
  var с = читать('yasna_custom_v1', []);
  return Array.isArray(с) ? с : [];
}

function партии() {
  var д = читать('yasna_duel_data', null);
  if (!д) return { партий: 0, тем: 0 };
  var темы = д.themeMastery || д.мастерство || {};
  return { партий: (д.history || д.партии || []).length, тем: Object.keys(темы).length };
}

/* ─── Состояние одного узла ────────────────────────────────────────── */

function состояние(у) {
  if (!у) return { код: 'нет' };
  if (у.нет) return { код: 'пишется', текст: 'в приложении пока нет' };

  var м = своё()[у.id] || {};
  var пройдены = пройденныеУроки();

  if (у.жанр === 'урок') {
    if (у.ключ === 'yasna_learn_intro_done_v1') {
      return строка(у.ключ) === '1'
        ? { код: 'пройдено', текст: 'дошли до конца' }
        : (м.открывал ? { код: 'начато', текст: 'начато' } : { код: 'нет' });
    }
    if (у.ключ === 'yasna_neg_lessons_v1') {
      var н = переговоры();
      if (н >= 4) return { код: 'пройдено', текст: 'все четыре пройдены' };
      if (н > 0) return { код: 'начато', текст: 'пройдено ' + н + ' из 4' };
      return { код: 'нет' };
    }
    if (пройдены.indexOf(у.id) >= 0) return { код: 'пройдено', текст: 'дошли до конца' };
    if (м.открывал) return { код: 'начато', текст: 'начато' };
    return { код: 'нет' };
  }

  if (у.жанр === 'разбор') {
    if (м.дошёл) return { код: 'пройдено', текст: 'просмотрен' };
    if (м.открывал) return { код: 'начато', текст: 'начат' };
    return { код: 'нет' };
  }

  if (у.жанр === 'круг') {
    var р = раскладки();
    var ясна = (у.адрес || '').match(/yasna=([^&]+)/);
    var к = ясна ? decodeURIComponent(ясна[1]) : null;
    var з = к && р[к];
    if (з && з.верно >= 10) return { код: 'держится', текст: 'разложено ' + з.верно + ' из 12' };
    if (з) return { код: 'пройдено', текст: 'разложено ' + (з.верно || 0) + ' из 12' };
    return { код: 'нет' };
  }

  if (у.жанр === 'своё') {
    var с = свои();
    if (с.length) {
      var полные = с.filter(function (я) { return (я.p || []).filter(Boolean).length === 12; }).length;
      return { код: полные ? 'пройдено' : 'начато',
               текст: с.length === 1 ? 'один круг' : с.length + ' круга' };
    }
    return { код: 'нет' };
  }

  if (у.жанр === 'вопросы') {
    if (у.id === 'kniga_sutki_voprosy') {
      var п = партии();
      if (п.партий > 0) return { код: 'начато', текст: 'сыграно партий: ' + п.партий };
      return { код: 'нет' };
    }
    return м.открывал ? { код: 'начато', текст: 'открывали' } : { код: 'нет' };
  }

  /* справка, книга, записи — состояния не имеют, только «открывали» */
  return м.открывал ? { код: 'начато', текст: 'открывали' } : { код: 'нет' };
}

/* ─── Куда вернуться ──────────────────────────────────────────────────
   Первое незаконченное занятие по порядку дерева: сначала метод, потом
   явления. Ищем начатое; если начатого нет — первое неоткрытое. */
function продолжить() {
  var Д = window.YasnaDerevo;
  if (!Д) return null;
  var узлы = Д.всеУзлы().filter(function (у) {
    return !у.нет && у.адрес && (у.жанр === 'урок' || у.жанр === 'разбор');
  });
  var начатое = null, первое = null;
  узлы.forEach(function (у) {
    var с = состояние(у);
    if (!начатое && с.код === 'начато') начатое = { узел: у, состояние: с };
    if (!первое && с.код === 'нет') первое = { узел: у, состояние: с };
  });
  return начатое || первое || null;
}

/* ─── Счёт по-честному: только среди написанного ──────────────────── */
function счёт() {
  var Д = window.YasnaDerevo;
  if (!Д) return { всего: 0, пройдено: 0 };
  var занятия = Д.всеУзлы().filter(function (у) {
    return !у.нет && (у.жанр === 'урок' || у.жанр === 'разбор');
  });
  var п = занятия.filter(function (у) {
    var к = состояние(у).код;
    return к === 'пройдено' || к === 'держится';
  }).length;
  return { всего: занятия.length, пройдено: п };
}

function когдаПоследнийРаз() {
  var д = своё(), т = 0;
  Object.keys(д).forEach(function (k) { if (д[k] && д[k].когда > т) т = д[k].когда; });
  return т || 0;
}

function поВетви(в) {
  var всего = 0, пройдено = 0, пишется = 0;
  (в.узлы || []).forEach(function (у) {
    if (у.нет) { пишется++; return; }
    всего++;
    var к = состояние(у).код;
    if (к === 'пройдено' || к === 'держится') пройдено++;
  });
  return { всего: всего, пройдено: пройдено, пишется: пишется };
}

window.YasnaZnanie = {
  состояние: состояние,
  продолжить: продолжить,
  счёт: счёт,
  поВетви: поВетви,
  когдаПоследнийРаз: когдаПоследнийРаз,
  отметить: записать
};

})();
