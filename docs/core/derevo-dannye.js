/* Паспорта: имя, объём и подзаголовок урока берутся из самого файла урока
   (сборка выпускает core/pasporta.js). Рукопись дерева хранит только то,
   чего файл не знает: ветвь, источник, «о», места-переопределения.
   Иначе имена расходились: «Учимся находить опоры» ↔ «Четыре опоры». */
(function наложитьПаспорта() {
  var П = (typeof window !== 'undefined' && window.YasnaPasporta) || null;
  if (!П) return;
  var поId = {};
  П.forEach(function (п) { поId[п.id] = п; });
  ВЕТВИ.forEach(function (в) {
    (в.узлы || []).forEach(function (у) {
      var п = поId[у.id];
      if (!п) return;
      у.имя = п.имя || у.имя;
      у.объём = п.объём || у.объём;
      if (п.часть) у.часть = п.часть;
      if (!у.места || !у.места.length) у.места = п.места || [];
      if (!у.о && п.под) у.о = п.под;
    });
  });
})();

function всеУзлы() {
  var сп = [];
  ВЕТВИ.forEach(function (в) {
    в.узлы.forEach(function (у) { сп.push(Object.assign({ ветвь: в.id, ветвьИмя: в.имя }, у)); });
  });
  return сп;
}

