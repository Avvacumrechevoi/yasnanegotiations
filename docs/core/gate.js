/* ═══════════════════════════════════════════════════════════════════
   core/gate.js — замок страниц. Открыта только главная, остальное по паролю.

   ╔═══════════════════════════════════════════════════════════════════╗
   ║  ЭТО ЗАНАВЕСКА НА ВРЕМЯ СТРОЙКИ, А НЕ ЗАЩИТА.                     ║
   ║                                                                   ║
   ║  Сайт раздаётся статикой с GitHub Pages, репозиторий публичный.   ║
   ║  Значит: (1) lessons/*.js, content.bundle.js, dist/*.min.js       ║
   ║  качаются по прямой ссылке мимо любого замка; (2) этот файл тоже  ║
   ║  открыт, и человек с консолью снимает замок одной строкой.        ║
   ║                                                                   ║
   ║  Замок решает ровно одну задачу: пока не выстроены серверная      ║
   ║  выдача контента и покупки — не пускать посторонних смотреть      ║
   ║  недоделанное. Настоящее закрытие наступит, когда тексты и        ║
   ║  вопросы начнёт отдавать сервер по токену.                        ║
   ╚═══════════════════════════════════════════════════════════════════╝

   ПОЧЕМУ В КОДЕ ХЕШ, А НЕ ПАРОЛЬ. Пароль в открытом виде лежал бы и на сайте,
   и в публичном репозитории — то есть был бы виден всем и навсегда остался бы
   в истории git. Хеш прячет его от чтения. От ПОДБОРА он не спасает: пароль
   короткий, перебор занимает секунды. Это осознанный размен ради временной
   меры, а не защита.

   ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ЧАСТЬ access.js. У access.js другая работа и
   намеренно другая политика: он резолвит ПРАВА на узлы каталога и работает
   fail-open (нет данных — считаем можно). Замок обязан вести себя наоборот:
   нет признака — не пускаем. Смешивать две противоположные политики в одном
   модуле — верный способ однажды случайно открыть всё или закрыть всё.

   ПОЧЕМУ РЕДИРЕКТ, А НЕ ЭКРАН ПОВЕРХ СТРАНИЦЫ. Если рисовать заглушку поверх,
   страница всё равно догрузится и выполнит свои скрипты: сходит в сеть,
   заведёт таймеры, запишет прогресс. Редирект до загрузки остального не даёт
   закрытой странице начаться вообще — при условии, что этот файл подключён
   ПЕРВЫМ. Отсюда требование: <script src=".../core/gate.js"> идёт раньше
   любых других скриптов страницы.

   FAIL-OPEN ПРИ ПОЛОМКЕ САМОГО ЗАМКА. Если localStorage недоступен (приватный
   режим Safari) или внутри что-то бросило исключение — пускаем. Замок, который
   от собственной ошибки закрывает сайт всем, включая владельца, хуже
   отсутствия замка.
   ═══════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var PASS_KEY = 'yasna_gate_pass';   // признак «пароль введён» на этом устройстве

  /* Открытые адреса. Держим списком, а не «всё кроме», чтобы новая страница
     по умолчанию была ЗАКРЫТОЙ — забыть закрыть опаснее, чем забыть открыть.
     Сюда же добавятся будущие демо-страницы. */
  var OPEN = [
    '/',                 // лендинг
    '/index.html',       // он же по прямому имени
    '/404.html',         // страница ошибки: закрывать её незачем
  ];

  try {
    var path = location.pathname;

    /* Сайт живёт и в подкаталоге (github.io/yasnanegotiations/), и в корне
       своего домена. Считаем путь относительно корня сайта, иначе на github.io
       ни один адрес из OPEN не совпадёт и закроется даже лендинг. */
    var base = '';
    var m = path.match(/^\/[^/]+\//);
    if (location.hostname.indexOf('github.io') > -1 && m) base = m[0].slice(0, -1);
    var rel = path.slice(base.length) || '/';

    for (var i = 0; i < OPEN.length; i++) {
      if (rel === OPEN[i]) return;                       // открыто — уходим молча
    }

    var ok = '';
    try { ok = window.localStorage.getItem(PASS_KEY) || ''; } catch (_) { return; }
    if (ok === '1') return;                               // пароль уже вводили

    /* Пароля нет. Уводим на главную с запросом пароля и запоминаем, куда шли.
       replace, а не href: закрытая страница не должна оставаться в истории,
       иначе «назад» после ввода возвращает на неё же до применения признака. */
    var back = rel + location.search + location.hash;
    location.replace(base + '/?lock=1&back=' + encodeURIComponent(back));
  } catch (e) {
    /* см. FAIL-OPEN выше */
    try { console.warn('[gate] пропускаю из-за ошибки замка:', e); } catch (_) {}
  }
})();
