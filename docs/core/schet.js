/* ═══════════════════════════════════════════════════════════════════════
   ЕДИНЫЙ СЧЁТ: СКОЛЬКО В ПРИЛОЖЕНИИ ЯСН, СЛОВ И МЕСТ.

   ЗАЧЕМ. На один вопрос «сколько тут ясн» приложение отвечало четырьмя
   числами сразу: «16 разобрано» на Уроках, «Сорок четыре явления» в Разборе,
   «0 / 10 тем открыто» в Играх и «6 тем» в описании страницы Игр. Все они
   были вписаны руками в текст экрана — и разошлись с данными в первый же
   день, потому что данные растут, а строка в разметке нет. Здесь числа
   считаются из самих данных, и экран берёт их отсюда, а не пишет цифру.

   ЧТО ЧЕМ СЧИТАЕТСЯ — сущности разные, складывать их нельзя:
     ясна (явление) — круг из двенадцати мест; готовые лежат в core/data.js;
     занятие        — урок, разбор, раскладка; лежат в core/derevo-dannye.js;
     тема вопросов  — третья сущность со своим источником (банк вопросов
                      игры). Здесь она НЕ считается нарочно: «44 ясны» и
                      «10 тем» — про разное, и общего числа у них нет.

   Источники подключать необязательно: чего нет, о том функция вернёт null,
   и экран покажет строку без числа, а не «undefined».

   Экспорт: window.YasnaSchet. Обычный script-тег ПОСЛЕ core/data.js и
   core/derevo-dannye.js — считает в момент вызова, не при загрузке.
   ═══════════════════════════════════════════════════════════════════════ */
(function () {
'use strict';

function данные() { return (typeof window !== 'undefined' && window.YasnaData) || null; }
function дерево() { return (typeof window !== 'undefined' && window.YasnaDerevo) || null; }

/* Сколько явлений уже разложено по кругу. Это и есть «Готовые ясны»:
   ровно тот перечень, который открывает окно выбора в Разборе. */
function готовыхЯсн() {
  var Д = данные();
  return (Д && Д.T) ? Д.T.length : null;
}

/* У скольких из них в приложении есть занятия. Ветвь дерева знаний считается
   только вместе с полем «ясна» (значит, у явления есть готовый круг) и хотя
   бы одним узлом — иначе строка обещала бы занятие, которого нет. */
function сЗанятиями() {
  var Д = дерево();
  if (!Д || !Д.ВЕТВИ) return null;
  var н = 0;
  Д.ВЕТВИ.forEach(function (в) {
    if (в.группа === 'ясна' && в.ясна && (в.узлы || []).length) н++;
  });
  return н;
}

/* Явления, разобранные на занятиях, но в приложение ещё не набранные.
   Пишем их числом и именами, без обещаний и без сроков. */
function пишется() {
  var Д = дерево();
  return (Д && Д.ПИШЕТСЯ) ? Д.ПИШЕТСЯ.length : null;
}

/* Слов в Словаре и мест в круге. Мест всегда двенадцать — но берём длину
   перечня ролей, а не число: перечень и есть источник. */
function словарь() {
  var Д = данные();
  return (Д && Д.GLOSS) ? Д.GLOSS.length : null;
}
function мест() {
  var Д = данные();
  return (Д && Д.REF) ? Д.REF.length : null;
}

window.YasnaSchet = {
  готовыхЯсн: готовыхЯсн,
  сЗанятиями: сЗанятиями,
  пишется: пишется,
  словарь: словарь,
  мест: мест
};

})();
