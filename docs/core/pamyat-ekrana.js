/* ═══════════════════════════════════════════════════════════════════
   core/pamyat-ekrana.js — память экрана между переходами.

   ЗАЧЕМ. Приложение многостраничное: тап по вкладке наббара — это
   location.replace, то есть НОВЫЙ документ. Всё, что человек навёл на
   экране руками, умирает вместе с прежним: прокрутка, раскрытые ветви
   дерева, раскрытые вопросы. Вернувшись на «Уроки» после Игр, человек
   каждый раз начинает с верха свёрнутого дерева. Нижняя навигация так
   себя не ведёт нигде: она обещает найти вкладку такой, какой её
   оставили, и это единственное её обещание, которое здесь нарушалось.

   ЧТО ДЕЛАЕТ. Пишет состояние экрана в sessionStorage по имени экрана —
   перед уходом (pagehide), при сворачивании приложения
   (visibilitychange) и при объявленном уходе на другую вкладку
   (yasna:уход) — и возвращает его на следующей загрузке.

   ПОЧЕМУ ВОЗВРАТ ЗОВЁТ САМА СТРАНИЦА, а не этот файл по DOMContentLoaded:
   прокрутку можно вернуть только когда содержимое уже есть, иначе
   документ короткий и прокручивать некуда. Миг, когда содержимое есть,
   знает только страница — у одной оно в разметке, у другой рисуется
   скриптом. Вызов стоит там же, где отрисовка, и возврат происходит в том
   же кадре: прыжка не видно.

   КАК ПОДКЛЮЧИТЬ (две строки на экран):
       <script src="core/pamyat-ekrana.js?v=1"></script>
       <script>window.ЯснаПамять && ЯснаПамять.помнить('rating');</script>
   Вторая строка ставится ПОСЛЕ содержимого (конец <body>) или сразу
   после своей отрисовки. По умолчанию помнит прокрутку и раскрытые
   <details> — этого хватает и длинной странице, и дереву узлов.

   Своё состояние — парой собрать()/вернуть():
       ЯснаПамять.помнить('learn', {
         ветви: '.dr-vetv',                       // свой отбор ветвей
         собрать: function () { return {чип: чип}; },  // null — не сохранять
         вернуть: function (своё) { ... }
       });
   собрать(), вернувшая null, означает «сейчас запоминать нечего»: прежнее
   сохранённое остаётся нетронутым. Так экран не подменяет прокрутку
   каталога прокруткой открытого поверх него занятия.
   ═══════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';

  var ПРИСТАВКА = 'yasna_ekran_v1:';
  /* sessionStorage не переживает убийство процесса, а Android убивает
     WebView и на смене масштаба шрифта, и просто по нехватке памяти.
     Зеркало в localStorage живёт полчаса — ровно как зеркало стека
     навигации (app/navigatsiya.js): человек, вернувшийся через минуту, не
     должен обнаружить экран заново свёрнутым. */
  var СРОК = 30 * 60 * 1000;

  function ключ(имя) {
    if (!имя) имя = (location.pathname.split('/').pop() || 'index.html');
    return ПРИСТАВКА + имя;
  }

  function прочитать(имя) {
    var к = ключ(имя), з = null;
    try { з = JSON.parse(sessionStorage.getItem(к) || 'null'); } catch (_) {}
    if (!з) {
      try {
        var м = JSON.parse(localStorage.getItem(к) || 'null');
        if (м && (Date.now() - (м.когда || 0)) < СРОК) з = м.что;
      } catch (_) {}
    }
    return з && typeof з === 'object' ? з : null;
  }

  function записать(имя, что) {
    var к = ключ(имя);
    try { sessionStorage.setItem(к, JSON.stringify(что)); } catch (_) {}
    try { localStorage.setItem(к, JSON.stringify({ что: что, когда: Date.now() })); } catch (_) {}
  }

  function забыть(имя) {
    try { sessionStorage.removeItem(ключ(имя)); } catch (_) {}
    try { localStorage.removeItem(ключ(имя)); } catch (_) {}
  }

  /* Ветвь узнаём по имени, а не по номеру: список перерисовывается
     (пройденные сценарии, новые узлы дерева), и номер после перерисовки
     показывает на чужую ветвь — раскрылась бы не та. */
  function имяВетви(э, i) {
    if (э.id) return э.id;
    var с = э.querySelector('summary');
    var т = с ? (с.textContent || '').replace(/\s+/g, ' ').trim() : '';
    return т ? т.slice(0, 80) : ('№' + i);
  }

  function собратьВетви(сел) {
    var имена = [], список = document.querySelectorAll(сел);
    for (var i = 0; i < список.length; i++)
      if (список[i].open) имена.push(имяВетви(список[i], i));
    return имена;
  }

  function вернутьВетви(сел, имена) {
    if (!имена || !имена.length) return;
    var список = document.querySelectorAll(сел);
    for (var i = 0; i < список.length; i++)
      if (имена.indexOf(имяВетви(список[i], i)) >= 0) список[i].open = true;
  }

  function куда() {
    return window.pageYOffset ||
      (document.documentElement && document.documentElement.scrollTop) || 0;
  }

  /* Прокрутку ставим сразу и повторяем несколько кадров: шрифты и картинки
     догружаются, документ растёт, и одного раза мало — экран замер бы выше
     нужного места. Плавности здесь быть не должно: человек не просил
     анимации, он просто вернулся на вкладку, и она обязана выглядеть так,
     будто никуда не уходила. Первое же касание пальцем отменяет доводку —
     спорить с рукой нельзя. */
  function вернутьПрокрутку(y) {
    if (!(y > 0)) return;
    var кадров = 0, брошено = false;
    function бросить() { брошено = true; }
    var события = ['touchstart', 'wheel', 'keydown', 'pointerdown'];
    for (var i = 0; i < события.length; i++)
      window.addEventListener(события[i], бросить, { passive: true });

    function прыгнуть() {
      try { window.scrollTo({ top: y, left: 0, behavior: 'auto' }); }
      catch (_) { window.scrollTo(0, y); }
    }
    function шаг() {
      if (брошено) return снять();
      прыгнуть();
      кадров++;
      /* Двадцати кадров (≈0,3 с) хватает на догрузку; дальше держать экран
         за руку — значит мешать. */
      if (кадров > 20 || (кадров > 2 && Math.abs(куда() - y) < 2)) return снять();
      if (window.requestAnimationFrame) requestAnimationFrame(шаг); else снять();
    }
    function снять() {
      for (var k = 0; k < события.length; k++) window.removeEventListener(события[k], бросить);
    }
    прыгнуть();
    if (window.requestAnimationFrame) requestAnimationFrame(шаг);
  }

  function помнить(имя, о) {
    о = о || {};
    var сел = (о.ветви === undefined) ? 'details' : о.ветви;
    var сохранённое = прочитать(имя) || {};

    if (сел) вернутьВетви(сел, сохранённое.ветви);
    if (о.вернуть) { try { о.вернуть(сохранённое.своё, сохранённое); } catch (_) {} }
    /* Якорь в адресе сильнее памяти: человек шёл по прямой ссылке в
       определённое место экрана, а не возвращался на вкладку. */
    if (о.прокрутка !== false && !location.hash) вернутьПрокрутку(сохранённое.прокрутка);

    function сохранить() {
      var с = {};
      if (о.собрать) {
        var своё;
        try { своё = о.собрать(); } catch (_) { своё = null; }
        if (своё === null || своё === undefined) return;   /* запоминать нечего */
        с.своё = своё;
      }
      if (сел) с.ветви = собратьВетви(сел);
      if (о.прокрутка !== false) с.прокрутка = куда();
      записать(имя, с);
    }

    /* pagehide приходит и при переходе, и при уходе в фон; visibilitychange
       страхует на Android, где документ иногда убивают без pagehide;
       yasna:уход шлёт наббар перед сменой вкладки — самый честный миг. */
    window.addEventListener('pagehide', сохранить);
    window.addEventListener('yasna:уход', сохранить);
    document.addEventListener('visibilitychange', function () {
      if (document.visibilityState === 'hidden') сохранить();
    });

    return { сохранить: сохранить, забыть: function () { забыть(имя); } };
  }

  window.ЯснаПамять = {
    помнить: помнить,
    прочитать: прочитать,
    записать: записать,
    забыть: забыть
  };
})();
