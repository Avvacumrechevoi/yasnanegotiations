/* ═══════════════════════════════════════════════════════════════════════════
   СНИМОК ПЕРВОЙ СТРАНИЦЫ ЛЕНТЫ В БАКЕТЕ — lenta/snimok.json.

   ЗАЧЕМ. 06.09.2026 домен шлюза резолвится (158.160.171.31), но TCP 443 к
   нему не открывается — ни с машины разработчика, ни с телефона владельца,
   ни из эмулятора; внешний ревьюер накануне получал от того же шлюза 200.
   То есть шлюз жив, а дороги до него из части сетей нет. При этом
   storage.yandexcloud.net отвечает за 0,7 с и отдаёт объекты бакета
   yasnalab.ru анонимно — через него же приложение и обновляется, значит до
   хранилища дорога есть у всех, у кого работает обновление.

   Отсюда решение: сборщик, у которого есть и база, и право писать в бакет,
   после каждого захода кладёт рядом с картинками СНИМОК первой страницы
   ленты. Приложение читает его из хранилища и показывает ленту, даже когда
   шлюз недоступен; шлюз остаётся для листания «Показать ещё», фильтров по
   управлению, счёта новых и жалоб.

   ФОРМА — РОВНО ОТВЕТ РУЧКИ. Снимок обязан разбираться тем же кодом клиента,
   что и ответ GET /lenta?n=20 без фильтра, поэтому он и СОБИРАЕТСЯ тем же
   кодом: lenta.js собратьСтраницу(). Второго списка правил (перемежение,
   skryto, Rutube только под видом «Видео», sobrano_at по источникам выдачи)
   здесь нет и быть не должно — первое же расхождение человек увидел бы как
   «в сети лента одна, без сети другая».

     { v: 1, snyato_at, sobrano_at, zapisi: […20], dalshe, upravleniya_s_zapisyami }

   v — версия формата: клиент, встретив незнакомую, снимок не разбирает.
   snyato_at — когда снят сам снимок; sobrano_at — свежесть данных, то же
   поле, что и в ответе ручки (его и показывают человеку).

   ПИШЕМ ТОЛЬКО ПРИ ИЗМЕНЕНИИ. Перед записью читаем то, что уже лежит в
   бакете, и сравниваем содержимое: ключи записей, dalshe, управления с
   записями и sobrano_at. Совпало — PUT не делаем вовсе: заход, в котором
   ни один источник не ответил (а сейчас это обычный ход дел), не должен
   переписывать снимок и сбивать кэш телефонам. snyato_at в сравнение не
   входит: он меняется каждый заход, и по нему снимок переписывался бы всегда.

   КЭШ — ДВЕ МИНУТЫ. Картинки лежат с max-age=604800: копия отозванного фото
   не должна год жить в кэше телефонов, но и меняться она не может. Снимок —
   наоборот: он меняется каждые четверть часа, и человек должен получать
   свежее в пределах пары минут, а не суток. Отсюда свой Cache-Control.

   ЗАВИСИМОСТИ ВНЕДРЯЮТСЯ (о.бакет, о.взять, о.сейчас, о.страницаЛенты) —
   как во всём сборщике: проба server/proby/proba-sbor.mjs идёт без сети и
   без облака.
   ═══════════════════════════════════════════════════════════════════════════ */
'use strict';

const Л = require('./lenta.js');

const КЛЮЧ = 'lenta/snimok.json';          /* рядом с lenta/telegram/ и lenta/vhod/ */
const ВЕРСИЯ = 1;
const ЗАПИСЕЙ = 20;                        /* столько же, сколько отдаёт GET /lenta без n */
const ТИП = 'application/json';
const КЭШ = 'public, max-age=120';
const СРОК_ЧТЕНИЯ_МС = 15000;
const МАКС_ПРИЧИНЫ = 200;

function коротко(с, n) { return String(с == null ? '' : (с.message || с)).slice(0, n || МАКС_ПРИЧИНЫ); }
function секунды(мс) { return new Date(мс).toISOString().slice(0, 19) + 'Z'; }

/* Помощники разбора строк YDB — те же, что даёт ручкам auth-email.js
   (txt/num/ts). Снимок собирается ТЕМ ЖЕ кодом, значит и колонки должны
   разбираться теми же тремя функциями, иначе «тот же код» кончился бы на
   первой же дате. */
function помощники(ydb) {
  return {
    TypedValues: ydb.TypedValues,
    Types: ydb.Types,
    txt: (v) => (v == null ? null : (v.textValue ?? null)),
    num: (v) => { const x = v?.uint64Value ?? v?.uint32Value ?? v?.int64Value ?? v?.int32Value; return x == null ? null : Number(String(x)); },
    ts: (v) => { const x = v?.uint64Value ?? v?.int64Value; return x == null ? null : new Date(Number(String(x)) / 1000).toISOString(); },
  };
}

/* Первая страница ленты из YDB — ровно то, что отдаёт GET /lenta?n=20 без
   фильтров. Источники читаются свежими: сборщик их только что переписал. */
function страницаЛентыYDB(drv, ydb) {
  const д = помощники(ydb);
  return async function страницаЛенты() {
    const { тело } = await Л.собратьСтраницу(drv, д, {
      upravlenie: null, tip: null, n: ЗАПИСЕЙ, курсор: null, после: null, свежие: true,
    });
    return тело;
  };
}

/* Снимок из тела страницы. Порядок ключей — как в договоре с клиентом. */
function снимокИз(тело, снятоISO) {
  return {
    v: ВЕРСИЯ,
    snyato_at: снятоISO,
    sobrano_at: (тело && тело.sobrano_at) || null,
    zapisi: (тело && тело.zapisi) || [],
    dalshe: (тело && тело.dalshe) || null,
    upravleniya_s_zapisyami: (тело && тело.upravleniya_s_zapisyami) || [],
  };
}

/* Содержимое снимка одной строкой — для сравнения с тем, что уже в бакете.
   Ключи записей (id) и их порядок, свежесть, курсор «дальше» и список
   управлений: всё, что человек увидит. snyato_at сюда не входит. */
function отпечаток(с) {
  if (!с || typeof с !== 'object') return null;
  const записи = Array.isArray(с.zapisi) ? с.zapisi : [];
  return JSON.stringify({
    v: с.v == null ? null : с.v,
    sobrano_at: с.sobrano_at || null,
    dalshe: с.dalshe || null,
    upravleniya: Array.isArray(с.upravleniya_s_zapisyami) ? с.upravleniya_s_zapisyami : [],
    /* Не только ключи: правка текста или подъехавшая картинка меняют
       карточку, не меняя id, и снимок обязан это подхватить. */
    zapisi: записи.map((з) => JSON.stringify(з)),
  });
}

/* Что лежит в бакете сейчас. Ошибка чтения — не беда: значит, сравнить не с
   чем, и снимок кладём. Хуже лишний PUT только отсутствие снимка. */
async function прежний(о) {
  if (!о.взять) return null;
  try {
    const р = await о.взять(о.бакет.адрес(КЛЮЧ), { срок: СРОК_ЧТЕНИЯ_МС });
    if (!р || р.статус !== 200 || !р.текст) return null;
    const с = JSON.parse(р.текст);
    return с && typeof с === 'object' ? с : null;
  } catch (e) { return null; }
}

/* Снять первую страницу и положить её в бакет, если содержимое изменилось.
   Возвращает { polozhen, sboj, prichina, zapisej }. sboj отделяет беду
   («не положили, а надо было») от обычного дела («содержимое то же, писать
   нечего»): строку в журнал вызывающий пишет только по sboj, иначе журнал
   собирал бы по строке каждые четверть часа ни о чём. Бросить может сборка
   страницы или сам PUT — заход от этого не падает, лови у вызывающего. */
async function сделатьСнимок(о) {
  if (!о.бакет) return { polozhen: false, sboj: true, prichina: 'бакета нет' };
  if (!о.страницаЛенты) return { polozhen: false, sboj: true, prichina: 'страницу ленты некому собрать' };
  const тело = await о.страницаЛенты();
  const снимок = снимокИз(тело, секунды(о.сейчас()));
  const было = await прежний(о);
  if (было && отпечаток(было) === отпечаток(снимок)) {
    return { polozhen: false, sboj: false, prichina: 'не изменилось', zapisej: снимок.zapisi.length };
  }
  await о.бакет.положить(КЛЮЧ, Buffer.from(JSON.stringify(снимок), 'utf8'), ТИП, КЭШ);
  return { polozhen: true, sboj: false, zapisej: снимок.zapisi.length, sobrano_at: снимок.sobrano_at };
}

exports.сделатьСнимок = сделатьСнимок;
exports.страницаЛентыYDB = страницаЛентыYDB;
exports.снимокИз = снимокИз;
exports.отпечаток = отпечаток;
exports.коротко = коротко;
exports.КЛЮЧ = КЛЮЧ;
exports.ВЕРСИЯ = ВЕРСИЯ;
exports.ЗАПИСЕЙ = ЗАПИСЕЙ;
exports.ТИП = ТИП;
exports.КЭШ = КЭШ;
