-- Миграция 002 — секрет устройства для гостевого доступа к прогрессу.
--
-- ЗАЧЕМ. В первой версии /progress владелец записи вычислялся как
-- `user_id || deviceId` без префикса пространства и без всякой проверки. Дыра
-- была воспроизведена на живом проде: зная идентификатор аккаунта, любой
-- человек БЕЗ токена читал чужой учебный прогресс и личные заметки к урокам
-- (GET /progress?deviceId=<чужой user_id>) и затирал их записью с большим rev.
-- Гостевые строки были защищены только знанием deviceId, который вдобавок
-- публиковался в ответе /leaderboard.
--
-- Теперь owner_key всегда с префиксом ('usr:' | 'dev:'), а гостевое
-- пространство требует секрет устройства: клиент держит его в localStorage
-- (yasna_device_secret_v1) и присылает заголовком X-Device-Secret. Здесь
-- хранится только sha256 — самого секрета сервер не знает.
--
-- Привязка при первом обращении (trust on first use): если строки нет, она
-- создаётся с присланным секретом. Слабее настоящей регистрации, но закрывает
-- реальный вектор — чтение чужих данных по подсмотренному идентификатору.
-- ═══════════════════════════════════════════════════════════════════

CREATE TABLE device_auth (
  device_id    Utf8 NOT NULL,
  secret_hash  Utf8 NOT NULL,          -- sha256(секрет), hex
  created_at   Timestamp NOT NULL,
  PRIMARY KEY (device_id)
);

-- Строки прогресса, записанные ДО введения префиксов, адресуются ключом без
-- пространства и теперь недостижимы ни для аккаунта, ни для гостя. Удаляем их:
-- это данные единственного тестового браузера за один день работы эндпоинта,
-- полные копии лежат в localStorage клиента и будут отправлены заново при
-- следующей синхронизации. Строки с правильным префиксом не затрагиваются.
DELETE FROM progress WHERE NOT (owner_key LIKE "usr:%" OR owner_key LIKE "dev:%");
DELETE FROM user_notes WHERE NOT (owner_key LIKE "usr:%" OR owner_key LIKE "dev:%");
DELETE FROM entitlements WHERE NOT (owner_key LIKE "usr:%" OR owner_key LIKE "dev:%");
