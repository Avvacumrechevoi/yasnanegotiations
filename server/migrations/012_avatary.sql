-- Миграция 012 — картинка аватара в самой базе и привязка секрета
-- устройства к карточке друга.
--
-- ЗАЧЕМ СЕКРЕТ В СТРОКЕ. До этой миграции право на карточку доказывалось
-- так: «есть заголовок X-Device-Secret — значит человек свой». Заголовок при
-- этом ни с чем не сверялся, а публичный адрес pid знает каждый, кто есть у
-- человека в друзьях (его отдаёт GET /druzya). Значит от чужого имени можно
-- было звать, убирать друзей и править карточку. Лечение то же, что в
-- /progress и в ленте: в строке лежит sha256 секрета, при первом обращении
-- он привязывается, дальше обязан совпадать. Токен вошедшего старше секрета.
--
-- ПОЧЕМУ КАРТИНКА В БАЗЕ, А НЕ В БАКЕТЕ. У служебного аккаунта облачных
-- функций нет права писать в хранилище, и выдать его отсюда нельзя. Вес
-- ограничен телефоном (квадрат 256 на 256, JPEG, не тяжелее 40 КБ) и ещё раз
-- проверяется сервером, поэтому строка остаётся маленькой.
--
-- ПОЧЕМУ ВЕРСИЯ ЧИСЛОМ. Адрес картинки несёт метку версии
-- (/druzya/avatar?pid=…&v=…), и по совпадению метки ответ отдаётся с вечным
-- кэшем. Метка обязана СТРОГО расти: иначе новая картинка не доедет до тех,
-- у кого прежняя уже в кэше.
--
-- ЧТО В МЕТКЕ. Секунды эпохи, умноженные на миллион, плюс случайный хвост.
-- Голых миллисекунд не хватило: два одновременных запроса (два телефона
-- одного человека) читают прежнее значение ДО того, как записал хоть один, и
-- получают одну и ту же метку, а на ней висит годовой кэш. Хвост случайный,
-- поэтому две разные картинки одну метку получить не могут, а запись идёт с
-- условием «только если версия выросла» и проверяется перечитыванием.
-- Прежние метки были в миллисекундах (около 1,8e12), новые — около 1,8e15
-- при потолке Uint64: рост не нарушен, места хватает с большим запасом.
--
-- ВСЕ НОВЫЕ КОЛОНКИ НЕОБЯЗАТЕЛЬНЫЕ. У людей, заведённых до этой миграции,
-- их нет, и NOT NULL сделал бы миграцию невыполнимой. Из этого же следует
-- правило записи: частичная запись — только UPDATE … WHERE pid, потому что
-- UPSERT в YDB требует ВСЕ NOT NULL колонки таблицы.
--
-- РАННЕР. scripts/apply-migrations.sh вырезает комментарии «--» и делит файл
-- по знаку конца утверждения, поэтому в пояснениях нет ни этого знака, ни
-- двойного дефиса внутри строковых литералов.
-- ═══════════════════════════════════════════════════════════════════

-- ─── доказательство права на строку ────────────────────────────────
-- sha256 секрета устройства в шестнадцатеричной записи, как в device_auth.
ALTER TABLE druzya_ludi ADD COLUMN secret_hash Utf8;

-- ─── картинка ──────────────────────────────────────────────────────
-- Сами байты JPEG. String — это байты, не текст.
ALTER TABLE druzya_ludi ADD COLUMN kartinka String;

ALTER TABLE druzya_ludi ADD COLUMN kartinka_tip Utf8;

-- Метка версии в миллисекундах эпохи, строго растущая.
ALTER TABLE druzya_ludi ADD COLUMN kartinka_v Uint64;

ALTER TABLE druzya_ludi ADD COLUMN kartinka_bajt Uint32;
