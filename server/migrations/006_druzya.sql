-- ЗАЧЕМ. До этого дружба жила в Realtime Database, а личностью человека была
-- запись в памяти телефона (yasna_pid_v1). Отсюда весь набор бед:
--   • переустановил приложение — стал другим человеком, друзья потеряны, а у
--     друзей остался висеть адрес, который никому не отвечает;
--   • «убрать друга» правило разрешает только в СВОЕЙ половине дерева, чужую
--     тронуть нельзя — убранный продолжал видеть и звать;
--   • согласие клалось в ящик otvety, и дружба завершалась лишь тогда, когда
--     позвавший сам откроет приложение и разберёт ящик;
--   • сменился код или личность — прежние узлы остаются в дереве навсегда:
--     клиентская уборка там невозможна (правила не фильтры, чтение каскадит);
--   • частоту заявок дерево не считает вовсе.
-- Ни одна из этих бед не чинится правилами: все они следуют из того, ГДЕ
-- лежат данные. Поэтому дружба переезжает сюда, к людям и прогрессу.
--
-- ЧТО ОСТАЁТСЯ В FIREBASE. Зовы в Партию — единственное, что здесь
-- действительно нужно в реальном времени: «тебя зовут» должно доехать за
-- секунды, пока человек смотрит на экран. Таблицы для этого не нужны.
--
-- ПОЧЕМУ ДВЕ СТРОКИ НА ПАРУ. Ключ (pid, drug_pid) даёт «моих друзей» одним
-- чтением по началу ключа, без сканов и вторичных указателей. Плата —
-- две строки вместо одной, и обе меняются ОДНИМ запросом в одной транзакции.
-- Это и есть лечение «убрал только у себя»: половины не могут разойтись.
--
-- ПЕРЕНОС СТАРЫХ. pid и код приходят от приложения как есть — строка
-- заводится по ним. Друзья, заведённые в дереве до переезда, не теряются:
-- обе стороны при первом заходе объявляются со своими прежними адресами.
-- ═══════════════════════════════════════════════════════════════════

-- ─── карточка человека в дружбе ────────────────────────────────────
-- Отдельно от users намеренно: дружба есть и у гостя, а users заводится
-- только при входе. Когда человек входит, строка привязывается к нему
-- (user_id), и на новом телефоне находится по аккаунту, а не по устройству.
CREATE TABLE druzya_ludi (
  pid         Utf8 NOT NULL,      -- публичный адрес, он же ключ дружбы
  user_id     Utf8,               -- заполняется при входе
  device_id   Utf8,               -- гостевая привязка
  nick        Utf8 NOT NULL,
  avatar      Utf8,
  kod         Utf8 NOT NULL,      -- шесть знаков, по нему человека находят
  created_at  Timestamp NOT NULL,
  updated_at  Timestamp NOT NULL,
  PRIMARY KEY (pid),
  -- Код ищется указателем, а не перебором. Уникальности YDB по вторичному
  -- индексу не даёт, поэтому её держит код функции: читаем перед записью и
  -- при занятости берём новый (пространство 28^6 ≈ 481 млн, столкновение —
  -- редкость, но обрабатывать его всё равно надо).
  INDEX druzya_ludi_by_kod GLOBAL ON (kod),
  INDEX druzya_ludi_by_user GLOBAL ON (user_id),
  INDEX druzya_ludi_by_device GLOBAL ON (device_id)
);

-- ─── связь ─────────────────────────────────────────────────────────
-- sostoyanie: 'poslal'  — я позвал, жду ответа
--             'prishla' — меня позвали, жду моего решения
--             'druzya'  — оба согласны
-- Обе половины пары пишутся и стираются одним запросом.
CREATE TABLE druzhba (
  pid         Utf8 NOT NULL,
  drug_pid    Utf8 NOT NULL,
  sostoyanie  Utf8 NOT NULL,
  created_at  Timestamp NOT NULL,
  updated_at  Timestamp NOT NULL,
  PRIMARY KEY (pid, drug_pid)
);
