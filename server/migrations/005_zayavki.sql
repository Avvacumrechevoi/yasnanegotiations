-- ═══════════════════════════════════════════════════════════════════
-- Миграция 005 — заявки «Посчитать имя».
--
-- ЗАЧЕМ. Человек хочет, чтобы имя посчитала команда Ясны, а не программа:
-- это разговор, а не функция. Значит нужна не форма-отправлялка, а заявка со
-- своим состоянием: подана — в работе — отвечено. Иначе получается кнопка,
-- которая глотает нажатие и ничего не обещает.
--
-- ПОЧЕМУ БАЗА, А НЕ ПИСЬМО. Письмо на общую почту решает половину задачи:
-- команда заявку увидит, а человек — нет. Здесь же состояние заявки видно
-- обеим сторонам, и в профиле честно написано «отправлено 5 сентября», а не
-- «спасибо, мы свяжемся» в никуда. Письмо остаётся уведомлением, но правда
-- живёт в таблице.
--
-- ПЕРСОНАЛЬНЫЕ ДАННЫЕ. Имя, дата рождения и способ связи — персональные
-- данные, и собираются они здесь ровно ради ответа. Поэтому:
--   • consent_at обязателен: без отметки о согласии заявка не создаётся;
--   • device_id хранится, чтобы СВОЮ заявку видел и невошедший человек, —
--     иначе гость отправил бы её в пустоту и не смог проверить состояние;
--   • ip_hash — только хеш, и только чтобы разобрать злоупотребления.
-- Удаление аккаунта личные поля заявки не трогает намеренно: заявка — это
-- обращение, на которое команда обязана ответить, и стирать его в момент
-- выхода нельзя. Разбор такого случая — руками, командой.
--
-- ПОЧЕМУ ГОСТЮ ТОЖЕ МОЖНО. Требовать вход ради одного обращения — потерять
-- половину обратившихся. Гость обязан оставить способ связи (вошедшему он
-- подставляется), и этого достаточно, чтобы ответить.
-- ═══════════════════════════════════════════════════════════════════

CREATE TABLE zayavki (
  zayavka_id  Utf8 NOT NULL,        -- uuid, он же публичный номер обращения
  vid         Utf8 NOT NULL,        -- 'imya' — что просят; поле на вырост
  user_id     Utf8,                 -- заполнено, если человек вошёл
  device_id   Utf8,                 -- по нему свою заявку видит и гость
  imya        Utf8 NOT NULL,        -- имя, которое просят посчитать
  rozhdenie   Utf8,                 -- дата рождения строкой, как ввели
  svyaz       Utf8 NOT NULL,        -- почта или телефон для ответа
  vopros      Utf8,                 -- пара слов от человека
  sostoyanie  Utf8 NOT NULL,        -- 'novaya' | 'v_rabote' | 'otvecheno'
  otvet       Utf8,                 -- что ответила команда (для истории)
  created_at  Timestamp NOT NULL,
  updated_at  Timestamp NOT NULL,
  consent_at  Timestamp NOT NULL,   -- согласие на обработку персональных данных
  ip_hash     Utf8,
  PRIMARY KEY (zayavka_id),
  -- Три разреза, в которых заявки читают на самом деле: «мои» (двумя
  -- способами — по человеку и по устройству) и «что разбирать» у команды.
  INDEX zayavki_by_user GLOBAL ON (user_id),
  INDEX zayavki_by_device GLOBAL ON (device_id),
  INDEX zayavki_by_sostoyanie GLOBAL ON (sostoyanie)
);
