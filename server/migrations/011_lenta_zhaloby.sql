-- Миграция 011 — очередь жалоб ленты: порядок в запросе и решение
-- «жалоба отклонена».
--
-- ЗАЧЕМ ИНДЕКС. /lenta/istochniki показывал разбирающему пятьдесят жалоб,
-- но выбирал их так: взять двести строк без порядка, отсортировать в памяти,
-- отрезать пятьдесят. При двухстах пятидесяти новых жалобах человек видел не
-- самые свежие, а случайные, и часть обращений не попадала к нему вовсе
-- (внешнее ревью 8.8, находка F17). Индекс (sostoyanie, at) даёт базе взять
-- ровно пятьдесят строк с конца: ORDER BY совпадает с ключом индекса.
-- Тот же индекс считает потолок «300 неразобранных» — по нему берётся не вся
-- таблица, а не больше трёхсот ключей.
--
-- ЗАЧЕМ ТРЕТЬЕ СОСТОЯНИЕ. Состояний было два: novaya и razobrana, причём
-- razobrana ставилась ТОЛЬКО скрытием записи. Значит у разбирающего был
-- выбор из двух зол: скрыть запись, которая ни в чём не виновата (жалоба
-- «реклама» на собственный анонс управления со скидкой), или оставить
-- жалобу висеть в очереди навсегда. Теперь есть otkloneno: жалоба закрыта,
-- запись осталась. Ставит его ручка POST /lenta/zhaloba/reshit, право
-- cap:lenta.moderate (то же, что у скрытия, — это одно и то же решение,
-- принятое в разные стороны).
--
-- Кто и когда решил — в reshil / reshenie_at, зачем — в reshenie_prichina.
-- Колонки необязательные: у прежних строк их просто нет.
--
-- ШЛЮЗ. Новый путь /lenta/zhaloba/reshit заведён в server/api-gateway.yaml
-- (POST + OPTIONS на функцию auth-telegram) и выкладывается вместе с
-- функцией: путей с шаблонами в спецификации нет, и без своей строки шлюз
-- ответил бы 404 сам, не вызывая функцию.
--
-- ОКНО ПОСТРОЕНИЯ ИНДЕКСА. ALTER TABLE ... ADD INDEX GLOBAL строится в фоне:
-- миграция возвращается раньше, чем индекс готов, и всё это время запрос
-- через VIEW отвечает ошибкой схемы. На этом же индексе висит потолок
-- ПУБЛИЧНОГО приёма жалоб, поэтому в окне обычный человек получал бы на
-- жалобу 503. Ждать готовности индекса в раннере не нужно: server/lenta.js
-- ловит «нет такого индекса» и повторяет тот же запрос без VIEW, обходом
-- маленькой таблицы (проба proba-lenta.mjs, раздел «Окно построения
-- индекса жалоб»). Порядок и предел при этом остаются в запросе.
--
-- РАННЕР. apply-migrations.sh вырезает комментарии «--» и делит файл по «,»,
-- поэтому в утверждениях ниже нет ни точки с запятой, ни двойного дефиса
-- внутри строковых литералов.
-- ═══════════════════════════════════════════════════════════════════

