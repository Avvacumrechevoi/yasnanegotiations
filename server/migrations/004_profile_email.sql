-- Миграция 004 — профиль пользователя и вход по почте.
--
-- ЗАЧЕМ. До этого войти можно было ТОЛЬКО через Telegram: регистрации как
-- таковой не существовало, пароля не было ни в каком виде, а из профиля в
-- users жили лишь ник и аватар. Для организаций это нерабочий сценарий —
-- Telegram есть не у всех сотрудников.
--
-- ПОЧЕМУ КОДЫ, А НЕ ПАРОЛИ. Вход по одноразовому коду из письма закрывает
-- сразу две задачи одним механизмом: и вход, и подтверждение почты (адрес
-- подтверждается самим фактом получения кода). При этом:
--   • пароли не хранятся вовсе — нечему утечь, не нужен «забыл пароль»,
--     не нужны требования к сложности;
--   • нет отдельного шага верификации, который люди бросают на половине.
-- Плата честная: каждый вход требует доступа к почте. Поэтому рядом —
-- «запомнить устройство» (долгий токен) и Telegram как второй способ.
-- Колонка password_hash заведена НА БУДУЩЕЕ и сейчас никем не пишется: если
-- пароль всё-таки понадобится (вход без доступа к почте), место готово и
-- миграция не потребуется.
--
-- ПЕРСОНАЛЬНЫЕ ДАННЫЕ. Имя, фамилия и телефон — персональные данные, поэтому
-- рядом с ними заведены consent_at (когда человек дал согласие) и deleted_at
-- (мягкое удаление аккаунта по требованию). Телефон НЕ обязателен — решение
-- владельца: обязательное поле отсекает часть людей на регистрации.
-- ═══════════════════════════════════════════════════════════════════

-- ─── профиль ───────────────────────────────────────────────────────
-- Только добавление колонок (в YDB новые колонки всегда nullable).
-- users.email и индекс users_by_email существуют с самого начала — схему
-- писали с расчётом на вход по почте, эта миграция достраивает остальное.
ALTER TABLE users ADD COLUMN first_name Utf8;
ALTER TABLE users ADD COLUMN last_name Utf8;
ALTER TABLE users ADD COLUMN phone Utf8;
ALTER TABLE users ADD COLUMN email_verified Bool;
ALTER TABLE users ADD COLUMN registered_via Utf8;   -- 'telegram' | 'email'
ALTER TABLE users ADD COLUMN consent_at Timestamp;  -- согласие на обработку ПД
ALTER TABLE users ADD COLUMN deleted_at Timestamp;  -- мягкое удаление
ALTER TABLE users ADD COLUMN password_hash Utf8;    -- на будущее, сейчас не пишется

-- ─── одноразовые коды ──────────────────────────────────────────────
-- Сам код НЕ хранится: только sha256(код + PEPPER). Иначе утечка таблицы =
-- возможность войти за любого, кто в этот момент запросил код.
-- Ключ (email, purpose): у адреса одновременно живёт один код на цель —
-- новый запрос затирает предыдущий, и это же гасит попытки «набрать кодов».
CREATE TABLE email_codes (
  email       Utf8 NOT NULL,
  purpose     Utf8 NOT NULL,        -- 'login' | 'change_email'
  code_hash   Utf8 NOT NULL,
  attempts    Uint32 NOT NULL,      -- неверных вводов; после 5 код мёртв
  expires_at  Timestamp NOT NULL,   -- 10 минут
  created_at  Timestamp NOT NULL,
  ip_hash     Utf8,                 -- для разбора злоупотреблений
  PRIMARY KEY (email, purpose)
);

-- ─── ограничение частоты ───────────────────────────────────────────
-- Считаем в двух разрезах: по адресу (чтобы не заваливать чужой ящик
-- письмами) и по IP (чтобы не перебирали адреса). Без этого форма входа
-- становится и спам-рассылкой, и проверялкой «есть ли такой человек».
CREATE TABLE auth_throttle (
  bucket       Utf8 NOT NULL,       -- 'email:<адрес>' | 'ip:<sha256>'
  window_start Timestamp NOT NULL,
  hits         Uint32 NOT NULL,
  PRIMARY KEY (bucket)
);

-- ─── долгие сессии устройства ──────────────────────────────────────
-- «Запомнить это устройство»: чтобы вход по коду не превращался в
-- ежедневный поход в почту. Хранится только хеш токена.
CREATE TABLE device_sessions (
  session_id  Utf8 NOT NULL,        -- uuid, он же публичная часть
  user_id     Utf8 NOT NULL,
  token_hash  Utf8 NOT NULL,        -- sha256(секрет сессии)
  device_id   Utf8,
  created_at  Timestamp NOT NULL,
  last_seen_at Timestamp NOT NULL,
  expires_at  Timestamp NOT NULL,
  revoked_at  Timestamp,
  user_agent  Utf8,
  PRIMARY KEY (session_id),
  INDEX device_sessions_by_user GLOBAL ON (user_id)
);
