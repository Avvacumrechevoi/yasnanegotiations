/* foto: N в описании записи → N разных адресов картинок. Раздаём адреса на
   этом шаге, чтобы каждый адрес на всех страницах был свой: проба про
   «не-JPEG» подменяет ответ по адресу и ждёт ровно одну неудачную запись. */
function разложитьФото(записи) {
  return записи.map((з) => {
    const сколько = typeof з.foto === 'number' ? з.foto : 0;
    if (!сколько) return з;
    return Object.assign({}, з, { foto: Array.from({ length: сколько }, () => адресФото()) });
  });
}

