/* Пёстрый узор: широкие полосы + мелкая рябь + равномерный шум. Пестрота нужна
   не для красоты, а чтобы пережатая копия 480 px весила как живая фотография
   (проба сверяет: миниатюра < 25 КБ, полная ≥ 25 КБ и < 90 КБ).

   Всё считается ЦЕЛЫМИ числами: Math.sin и деление с плавающей точкой в разных
   сборках V8 могут дать разный последний бит, и байты JPEG разошлись бы между
   машиной разработчика и раннером — а CI сверяет, что готовые файлы ровно те,
   что даёт этот сборщик. Треугольная волна вместо синуса ровно так же пёстрая. */
function треугольник(t, период, размах) {
  const п = период * 2;
  const м = ((t % п) + п) % п;
  const вверх = м < период ? м : п - м;                       /* 0 … период */
  return Math.trunc((вверх * 2 * размах) / период) - размах;  /* −размах … +размах */
}

function узор(ширина, высота) {
  const пикселей = Buffer.alloc(ширина * высота * 4);
  let зерно = 20260905 >>> 0;
  const шумок = () => { зерно = (Math.imul(зерно, 1664525) + 1013904223) >>> 0; return ((зерно >>> 20) % 13) - 6; };
  for (let y = 0; y < высота; y++) {
    for (let x = 0; x < ширина; x++) {
      const i = (y * ширина + x) * 4;
      const ш = шумок();
      const r = 128 + треугольник(x * 3 + y * 2, 149, 88) + треугольник(x * 7 + y, 23, 22) + ш;
      const g = 124 + треугольник(y * 5 - x, 173, 78) + треугольник(y * 6 - x, 19, 22) + ш;
      const b = 118 + треугольник(x + y, 97, 68) + треугольник(x + y * 3, 29, 22) + ш;
      пикселей[i] = Math.max(0, Math.min(255, r));
      пикселей[i + 1] = Math.max(0, Math.min(255, g));
      пикселей[i + 2] = Math.max(0, Math.min(255, b));
      пикселей[i + 3] = 255;
    }
  }
  return { data: пикселей, width: ширина, height: высота };
}

