function ключиВхода(kanal) {
  const п = ПРЕФИКС_ВХОДА + String(kanal) + '/';
  return { stranica: п + 'stranica.html', meta: п + 'meta.json', картинка: (адрес) => п + 'kartinki/' + сырьёSha1(адрес) + '.jpg' };
}

/* Сырьё канала из бакета: { текст, снято, возрастМин } или { нет: почему }.
   Причина возвращается словами — она уходит в журнал источника рядом с
   причиной сетевого сбоя, чтобы владелец видел обе половины: и что своя
   дорога закрыта, и почему не выручил почтальон. */
async function сырьёПочтальона(ист, о, сейчасМс) {
  if (!о.бакет) return { нет: 'сырьё некуда смотреть (нет бакета)' };
  if (ист.istochnik !== 'telegram') return { нет: 'почтальон возит только Телеграм' };
  const к = ключиВхода(ист.kanal);
  let мета;
  try {
    const р = await о.взять(о.бакет.адрес(к.meta), { срок: СРОК_СЫРЬЯ_МС });
    if (!р || р.статус !== 200 || !р.текст) return { нет: 'сырья нет (meta ' + (р && р.статус) + ')' };
    мета = JSON.parse(р.текст);
  } catch (e) { return { нет: 'сырьё: ' + коротко(e && e.message || e, 120) }; }
  if (!мета || typeof мета !== 'object') return { нет: 'сырьё: meta не объект' };
  /* Канал в meta должен совпасть с тем, за которым мы шли: иначе чужая
     страница легла бы в чужую ленту (сырьё пишет отдельная задача, ошибиться
     префиксом она может, а лента этого не заметит). */
  if (String(мета.kanal || '') !== String(ист.kanal)) return { нет: 'сырьё чужого канала: ' + коротко(мета.kanal, 60) };
  const снятоМс = Date.parse(мета.snyato || '');
  if (!Number.isFinite(снятоМс)) return { нет: 'сырьё без отметки времени' };
  const возрастМс = сейчасМс - снятоМс;
  if (возрастМс < -СЫРЬЁ_ИЗ_БУДУЩЕГО_МС) return { нет: 'сырьё из будущего' };
  if (возрастМс > СЫРЬЁ_СВЕЖЕСТЬ_МС) return { нет: 'сырьё старое (' + Math.round(возрастМс / 60000) + ' мин)' };
  let стр;
  try {
    const р = await о.взять(о.бакет.адрес(к.stranica), { срок: СРОК_СЫРЬЯ_МС });
    if (!р || р.статус !== 200 || !р.текст) return { нет: 'страницы нет в сырье (' + (р && р.статус) + ')' };
    стр = р.текст;
  } catch (e) { return { нет: 'сырьё: ' + коротко(e && e.message || e, 120) }; }
  return { текст: стр, снято: isoМс(снятоМс), возрастМин: Math.max(0, Math.round(возрастМс / 60000)) };
}

/* Ответ площадки (статус не 200, не-JPEG по сигнатуре, битые байты, размер
   больше предела) — это ПОПЫТКА: у записи такой картинки нет и через час не
   будет. Обрыв сети, отмена по сроку и отказ бакета попытку не тратят
   (ревью 8.8, F03): три подряд оборванных запроса из облака навсегда
   оставляли запись без картинки, хотя картинка на месте. */
function ошибкаПлощадки(сообщение, статус) {
  const e = new Error(сообщение);
  e.площадка = true;
  if (статус) e.статус = статус;
  return e;
}

async function картинкиВБакет(з, о) {
  let ответ;
  try {
    ответ = await о.взять(з.kartinka_istochnika, { срок: СРОК_КАРТИНКИ_МС, байты: true, максБайт: КАРТИНКА_МАКС_БАЙТ });
  } catch (e) {
    /* Слишком большой файл площадка объявляет сама (Content-Length) — это её
       ответ, а не обрыв. */
    if (/больше предела/.test(String(e && e.message || e))) throw ошибкаПлощадки(коротко(e && e.message || e, 200));
    e.сеть = true;
    throw e;
  }
  if (!ответ || ответ.статус !== 200 || !ответ.тело || !ответ.тело.length) throw ошибкаПлощадки('картинка: статус ' + (ответ && ответ.статус), ответ && ответ.статус);
  if (ответ.тело.length > КАРТИНКА_МАКС_БАЙТ) throw ошибкаПлощадки('картинка: ' + ответ.тело.length + ' байт, больше предела');
  let к;
  try { к = пережать(ответ.тело, о); }
  catch (e) { throw ошибкаПлощадки(коротко(e && e.message || e, 200)); }
  const ключи = ключиБакета(з);
  await о.бакет.положить(ключи.m, к.m, 'image/jpeg');   /* отказ бакета — не вина площадки: попытку не тратим */
  await о.бакет.положить(ключи.p, к.p, 'image/jpeg');
  return { kartinka: о.бакет.адрес(ключи.m), kartinka_polnaya: о.бакет.адрес(ключи.p), ширина: к.ширина, высота: к.высота };
}

/* Удалить оба объекта записи из бакета. Ключи считаются от klyuch, поэтому
   адрес в строке не нужен; 404 — тоже успех. */
async function удалитьОбъекты(з, о) {
  if (!о.бакет) return;
  const ключи = ключиБакета(з);
  await о.бакет.удалить(ключи.m);
  await о.бакет.удалить(ключи.p);
}

/* 403 на DELETE — это не сбой сети, а отсутствие права (storage.uploader
   вместо storage.editor). Такое не лечится повтором через 15 минут, и
   владелец должен увидеть это в состоянии источника, а не в логе функции. */
function нетПрава(e) { return !!(e && (e.код === 403 || /DELETE 403/.test(String(e.message || '')))); }

async function тревогаБакета(о, klyuch, сколько) {
  const сейчасМс = о.сейчас();
  const была = await о.хранилище.тревогаБыла(klyuch, isoМс(сейчасМс - ТРЕВОГА_ЧАСОВ * 3600000), ТРЕВОГА_БАКЕТА);
  if (была) return false;
  await о.хранилище.журнал({ klyuch, ishod: 'trevoga', novyh: 0, dlitelnost_ms: 0, otkuda: о.otkuda || 'timer',
    soobshchenie: ТРЕВОГА_БАКЕТА + ' (DELETE 403, не удалено ' + сколько + '): сервисному аккаунту нужна роль storage.editor' });
  return true;
}

/* ─── robots.txt ─────────────────────────────────────────────────────────── */
const роботы = new Map();      /* host → { когда, текст } — на жизнь экземпляра */
async function роботРазрешает(адрес, путь, о) {
  let host;
  try { host = new URL(адрес).host; } catch (e) { return { можно: false, почему: 'плохой адрес' }; }
  const мс = о.сейчас();
  let з = роботы.get(host);
  if (!з || мс - з.когда > ROBOTS_КЭШ_МС) {
    let текст = '';
    try {
      const р = await о.взять('https://' + host + '/robots.txt', { срок: СРОК_РОБОТОВ_МС });
      if (р && р.статус === 200 && р.текст) текст = р.текст;
    } catch (e) { текст = ''; /* нет файла или сети — считаем, что можно; сам заход покажет */ }
    з = { когда: мс, текст };
    роботы.set(host, з);
  }
  return Р.роботРазрешает(з.текст, путь, Р.АГЕНТ) ? { можно: true } : { можно: false, почему: 'robots.txt запрещает ' + путь };
}

/* ─── один источник ──────────────────────────────────────────────────────── */
function причинаСети(e) {
  const c = e && e.cause;
  if (!c) return '';
  const код = c.code || c.name || '';
  const адрес = c.address ? ' ' + c.address + (c.port ? ':' + c.port : '') : '';
  return код ? ' [' + код + адрес + ']' : (c.message ? ' [' + String(c.message).slice(0, 60) + ']' : '');
}

/* Одна страница с повтором при обрыве. Ответ со статусом (403, 302) — не
   повод повторять, а обрыв — повод, если бюджет позволяет. */
async function взятьСтраницу(адрес, о) {
  let ответ, сбой = null;
  for (let попытка = 0; попытка <= ПОВТОР_СТРАНИЦЫ; попытка++) {
    сбой = null;
    try { ответ = await о.взять(адрес, { срок: СРОК_ЗАПРОСА_МС }); break; }
    catch (e) { сбой = e; }
    if (попытка < ПОВТОР_СТРАНИЦЫ && о.остаток() > МИН_ОСТАТОК_МС + СРОК_ЗАПРОСА_МС) continue;
    break;
  }
  return { ответ, сбой };
}

/* Слить разбор ещё одной страницы в накопленное сырьё: записи без повторов,
   множества id и счётчики — суммой. */
function слитьСырьё(куда, ещё) {
  const видели = new Set(куда.записи.map((з) => з.id));
  for (const з of ещё.записи) if (!видели.has(з.id)) { видели.add(з.id); куда.записи.push(з); }
  for (const id of (ещё.наСтранице || [])) куда.наСтранице.add(id);
  if (ещё.отброшеноId && ещё.отброшеноId.reklama) куда.отброшеноId.reklama.push(...ещё.отброшеноId.reklama);
  for (const [к, n] of Object.entries(ещё.отброшено || {})) куда.отброшено[к] = (куда.отброшено[к] || 0) + (n || 0);
  for (const [к, n] of Object.entries(ещё.здоровье || {})) куда.здоровье[к] = (куда.здоровье[к] || 0) + (n || 0);
  return куда;
}

function наименьшийId(записи) {
  let м = null;
  for (const з of записи) {
    const n = Number(з.id);
    if (!Number.isFinite(n)) return null;
    if (м == null || n < м) м = n;
  }
  return м;
}

/* ДОБОР ПРОПУСКОВ (ревью 8.8, F05). Первая страница превью держит два-три
   десятка записей. Если сборщик молчал сутки (t.me из облака отвечает через
   раз), между самой старой записью страницы и самой новой в базе появляется
   дыра, и прежний сборщик её никогда не закрывал. Здесь: пока самая старая
   запись страницы новее последней сохранённой публикации канала — идём назад
   по ?before=<id>, не больше трёх страниц и не дольше минуты, и
   останавливаемся, как только на странице встретилась знакомая запись. */
async function добрать(сырьё, ист, о, разборщик, сейчасМс) {
  if (!разборщик.дальше || !ист.poslednyaya_publikaciya || !сырьё.записи.length) return 0;
  const известно = сек(ист.poslednyaya_publikaciya);
  const самаяСтарая = сырьё.записи.reduce((м, з) => (м && м < з.data ? м : з.data), null);
  if (!(самаяСтарая > известно)) return 0;                 /* дыры нет: страница смыкается с базой */
  const начало = Date.now();
  let страниц = 0, доId = наименьшийId(сырьё.записи);
  while (доId && страниц < ДОБОР_СТРАНИЦ) {
    if (Date.now() - начало > ДОБОР_СРОК_МС) break;
    if (о.остаток() < РЕЗЕРВ_ЗАПИСИ_МС + СРОК_ЗАПРОСА_МС) break;   /* остаток нужен на запись разобранного */
    const п = await взятьСтраницу(разборщик.дальше(ист, доId), о);
    if (п.сбой || !п.ответ || п.ответ.статус !== 200) break;
    let ещё;
    try { ещё = разборщик.разобрать(п.ответ.текст, ист, { своиКаналы: о.своиКаналы, сейчасМс }); }
    catch (e) { break; }
    if (Р.здоровьеПлохое(ещё.здоровье) || !ещё.записи.length) break;
    слитьСырьё(сырьё, ещё);
    страниц++;
    const низ = наименьшийId(ещё.записи);
    if (ещё.записи.some((з) => з.data <= известно)) break;         /* дошли до знакомого — дыра закрыта */
    if (низ == null || низ >= доId) break;                          /* площадка вернула то же самое */
    доId = низ;
  }
  return страниц;
}

/* ШАГ КАРТИНОК — отдельно от записи в базу и ПОСЛЕ неё (ревью 8.8, F02).
   Свой потолок: 30 с и 8 картинок на источник, плюс общий предохранитель
   захода. Обрыв по сроку функции здесь уже ничего не стоит: разобранное
   лежит в базе, итог и журнал написаны. */
async function шагКартинок(ист, о, разборщик, сейчасISO, почтальон) {
  const итоги = { собрано: 0, ошибок: 0, обрывов: 0, нетВСырье: 0, остановлено: false };
  о.картинки = о.картинки || { обрывов: 0, остановлены: false };
  if (!(разборщик.картинки && ист.soglasie_at && о.бакет)) return итоги;
  if (о.картинки.остановлены) { итоги.остановлено = true; return итоги; }
  if (о.остаток() < МИН_ОСТАТОК_КАРТИНКИ_МС) return итоги;
  const х = о.хранилище;
  const начало = Date.now();
  /* Страница пришла через почтальона — значит, площадка нам не отвечает, и
     cdn*.telesco.pe тоже не ответит. Картинки берём из его же сырья: ключ
     считается от адреса картинки, копии кладём в lenta/telegram/ как всегда,
     так что для ленты и телефонов ничего не меняется. */
  const вход = почтальон ? ключиВхода(ист.kanal) : null;
  const ждут = await х.безКартинки(ист, КАРТИНКА_ПОПЫТОК, КАРТИНОК_ЗА_ЗАХОД);
  for (const з of ждут) {
    if (о.картинки.остановлены) { итоги.остановлено = true; break; }
    if (Date.now() - начало > СРОК_КАРТИНОК_НА_ИСТОЧНИК_МС) break;
    if (о.остаток() < МИН_ОСТАТОК_КАРТИНКИ_МС) break;      /* остальные — в следующий раз, попытка не тратится */
    const попыток = Number(з.kartinka_popytok) || 0;
    const адресКартинки = вход ? о.бакет.адрес(вход.картинка(з.kartinka_istochnika)) : з.kartinka_istochnika;
    try {
      const к = await картинкиВБакет(Object.assign({ istochnik: ист.istochnik }, з, { kartinka_istochnika: адресКартинки }), о);
      await х.картинка(з.klyuch, к.kartinka, к.kartinka_polnaya, попыток, сейчасISO);
      итоги.собрано++;
      о.картинки.обрывов = 0;
    } catch (e) {
      /* Картинки нет в сырье (почтальон не довёз: старая запись, файл больше
         предела, поездка оборвалась) — это не ответ площадки: попытку не
         тратим, придёт следующим сырьём. */
      if (вход && e && e.площадка && e.статус === 404) { итоги.нетВСырье++; continue; }
      if (e && e.площадка) {
        await х.картинка(з.klyuch, null, null, попыток + 1, сейчасISO);
        итоги.ошибок++;
        о.картинки.обрывов = 0;
      } else {
        /* Обрыв сети или отказ бакета: попытку не тратим. Два подряд —
           хост недоступен, картинки этого захода прекращаем совсем. */
        итоги.обрывов++;
        о.картинки.обрывов++;
        if (о.картинки.обрывов >= ОБРЫВОВ_КАРТИНОК_ПОДРЯД) { о.картинки.остановлены = true; итоги.остановлено = true; }
      }
      console.warn('[lenta-sbor] ' + з.klyuch + ': '
        + (e && e.площадка ? 'попытка ' + (попыток + 1) + ' из ' + КАРТИНКА_ПОПЫТОК : 'обрыв, попытка не потрачена')
        + ': ' + коротко(e && e.message || e, 200) + причинаСети(e));
    }
  }
  return итоги;
}

async function собратьИсточник(ист, о) {
  const начало = Date.now();
  const сейчасМс = о.сейчас();
  const сейчасISO = isoМс(сейчасМс);
  const х = о.хранилище;
  const разборщик = Р.РАЗБОРЩИКИ[ист.istochnik];
  /* Через почтальона или своим ходом — решается ниже; отметка нужна и в
     журнале (otkuda), и шагу картинок. */
  let почтальон = null;
  const итогИст = (исход, сообщение, новых, доп) =>
    итог(ист, о, начало, исход, сообщение, новых, Object.assign({ otkuda: почтальон ? 'pochtalon' : null }, доп));
  if (!разборщик) return итогИст('propusk', 'нет разборщика для ' + ист.istochnik, 0);

  const адрес = разборщик.адрес(ист);
  const робот = await роботРазрешает(адрес, разборщик.путьРобота(ист), о);
  if (!робот.можно) return итогИст('otkaz_robots', робот.почему, 0);

  const первая = await взятьСтраницу(адрес, о);
  let ответ = первая.ответ, сбой = первая.сбой;
  /* СНАЧАЛА САМ, ПОТОМ ПОЧТАЛЬОН. Своей дороги нет — обрыв или сбой на
     стороне площадки (5xx): смотрим сырьё в бакете. Ответ со смыслом (302 у
     закрытого превью, 404 у переименованного канала, 403) почтальоном не
     лечится: он получил бы то же самое, а подмена сырьём только спрятала бы
     настоящую причину от владельца. */
  let почемуНеПочтальон = null;
  if (сбой || !ответ || ответ.статус >= 500) {
    /* Сырьё — это ещё два запроса (meta и страница) по 20 с. Если после
       обрыва страницы столько времени с резервом записи уже не осталось,
       к бакету не идём вовсе: иначе функцию убьют по сроку прямо на нём, и
       разобранное этого захода не легло бы никуда (ревью 8.8, F02 на дороге
       почтальона). Своей строкой в журнале это видно так же, как отказ. */
    const хватит = о.остаток() >= РЕЗЕРВ_ЗАПИСИ_МС + СРОК_СЫРЬЯ_ШАГ_МС;
    if (!хватит) почемуНеПочтальон = 'на сырьё не хватило срока функции (осталось ' + Math.round(о.остаток() / 1000) + ' с)';
    else {
      const с = await сырьёПочтальона(ист, о, сейчасМс);
      if (с.текст) { почтальон = с; ответ = { статус: 200, текст: с.текст }; сбой = null; }
      else почемуНеПочтальон = с.нет;
    }
  }
  const иПочтальон = почемуНеПочтальон ? '; почтальон: ' + почемуНеПочтальон : '';
  /* «fetch failed» без причины не отличить от блокировки: пишем код из
     e.cause (ECONNRESET, ETIMEDOUT, ENOTFOUND, CERT…) — по нему видно, режут
     ли t.me на пути из облака или просто медленно отвечают. */
  if (сбой) return итогИст('oshibka', 'сеть: ' + коротко(сбой && сбой.message || сбой) + причинаСети(сбой) + иПочтальон, 0);
  if (!ответ || ответ.статус !== 200) {
    return итогИст('oshibka', 'ответ ' + (ответ && ответ.статус) + (ответ && ответ.куда ? ' → ' + коротко(ответ.куда, 120) : '') + иПочтальон, 0);
  }

  let сырьё;
  try { сырьё = разборщик.разобрать(ответ.текст, ист, { своиКаналы: о.своиКаналы, сейчасМс }); }
  catch (e) { return итогИст('oshibka', 'разбор: ' + коротко(e && e.message || e), 0); }

  const плохо = Р.здоровьеПлохое(сырьё.здоровье);
  if (плохо) return итогИст('oshibka', плохо, 0, { название: сырьё.название });
  /* Ранний выход с ошибкой — только когда не распознан НИ ОДИН блок записи
     (ревью 8.8, F08). Страница, где все записи отсеяны фильтром (реклама),
     разобрана удачно: решения по известным id надо применить, иначе реклама
     висела бы в ленте, пока её не сменят новые записи. */
  const блоков = (сырьё.здоровье && сырьё.здоровье.блоков) || 0;
  if (!сырьё.записи.length && !сырьё.пусто && !блоков) return итогИст('oshibka', 'разметка: ни одного блока записи', 0, { название: сырьё.название });
  if (сырьё.пусто) return итогИст('pusto', 'в канале нет записей', 0, { название: сырьё.название });

  /* Добор назад по ?before= — только своим ходом: если площадка нам не
     отвечает, ходить к ней ещё три раза незачем, а в сырьё почтальон кладёт
     одну первую страницу. Пропуски доберутся, когда дорога откроется. */
  const доборСтраниц = почтальон ? 0 : await добрать(сырьё, ист, о, разборщик, сейчасМс);
  const всёОтфильтровано = блоков > 0 && !сырьё.записи.length;

  const записи = сырьё.записи.map((з) => нормализовать(з, ист, сейчасISO));
  const самаяСтарая = записи.reduce((м, з) => (м && м < з.data ? м : з.data), null);
  const самаяНовая = записи.reduce((м, з) => (м && м > з.data ? м : з.data), null);
  const ключ = (id) => ист.istochnik + ':' + ист.kanal + ':' + id;
  const прочитано = new Set(записи.map((з) => з.klyuch));
  /* Всё, что есть на странице до фильтров: разобранное, служебное, без даты,
     отсеянное стоп-словами. Разборщик отдаёт множество id; если его нет
     (чужой разборщик) — считаем страницей только прочитанное. */
  const наСтранице = new Set(сырьё.наСтранице ? [...сырьё.наСтранице].map(ключ) : прочитано);
  const реклама = new Set(((сырьё.отброшеноId && сырьё.отброшеноId.reklama) || []).map(ключ));
  const отб = сырьё.отброшено || {};

  /* Что уже лежит за то же окно — одним чтением по индексу канала. Если на
     странице не осталось ни одной записи (всё отфильтровано), окна нет:
     читаем весь срок хранения, чтобы применить решения по известным id. */
  const отISO = самаяСтарая || isoМс(сейчасМс - ХРАНИТЬ_ДНЕЙ * 86400000);
  const есть = new Map((await х.записиКанала(ист, отISO)).map((р) => [р.klyuch, р]));

  /* 1. Сверка. Удалённой считается запись, которой на странице НЕТ ВОВСЕ и
        которая лежит строго между самой старой и самой новой прочитанной:
        границы окна не трогаем — там могло просто закончиться листание.
        Запись, которую на этот раз не удалось прочитать (блок без даты),
        на странице есть — она не удалена, и трогать её нельзя; если таких
        блоков хоть один, границы окна неизвестны — сверку пропускаем целиком.
        Запись, отсеянная стоп-словами после того, как её уже собрали, —
        скрывается своей причиной 'reklama'. Авто-скрытая запись, снова
        прочитанная со страницы, воскресает: пропажа была сбоем разметки или
        площадки, а не удалением. */
  const сверкаМожно = !(отб.bez_daty > 0 || отб.bez_id > 0);
  let скрыто = 0, воскрешено = 0;
  for (const р of есть.values()) {
    if (наСтранице.has(р.klyuch)) {
      if (р.skryto && АВТО_ПРИЧИНЫ.includes(р.skryto_prichina) && прочитано.has(р.klyuch)) {
        await х.показать(р.klyuch, сейчасISO);
        р.skryto = false; р.skryto_prichina = null; р.kartinka_popytok = 0;
        воскрешено++;
      } else if (!р.skryto && реклама.has(р.klyuch)) {
        await х.скрыть(р.klyuch, 'reklama', сейчасISO);
        р.skryto = true; р.skryto_prichina = 'reklama';
        скрыто++;
      }
      continue;
    }
    if (р.skryto || !сверкаМожно || !самаяСтарая) continue;
    if (р.data > самаяСтарая && р.data < самаяНовая) {
      await х.скрыть(р.klyuch, 'udaleno_v_istochnike', сейчасISO);
      р.skryto = true; р.skryto_prichina = 'udaleno_v_istochnike';
      скрыто++;
    }
  }

  /* 2. Новые — с оглядкой на срок хранения (см. шапку: правило то же, что у
        уборки, иначе молчащий канал качался бы туда-сюда). */
  const порогХранения = isoМс(сейчасМс - ХРАНИТЬ_ДНЕЙ * 86400000);
  const объединение = записи.map((з) => ({ klyuch: з.klyuch, data: з.data }))
    .concat([...есть.values()].filter((р) => !наСтранице.has(р.klyuch) && !р.skryto).map((р) => ({ klyuch: р.klyuch, data: р.data })))
    .sort(поУбыванию);
  const место = new Map(объединение.map((з, i) => [з.klyuch, i]));
  const новые = записи.filter((з) => !есть.has(з.klyuch) && (з.data >= порогХранения || место.get(з.klyuch) < БЕЗ_СРОКА_ЗАПИСЕЙ));
  const заСроком = записи.filter((з) => !есть.has(з.klyuch)).length - новые.length;

  /* 3. Правки: окно 7 дней. Сравниваем отдельно текст и медиа — при замене
        фото в посте текст остаётся прежним, отпечаток тоже, и прежний
        сборщик новый адрес картинки не брал вовсе (ревью 8.8, F04). */
  const порогПравок = isoМс(сейчасМс - ОКНО_ПРАВОК_ДНЕЙ * 86400000);
  const числоИли = (v) => (v == null || v === '' ? null : Number(v));
  const медиаИное = (р, з) => (р.kartinka_istochnika || null) !== (з.kartinka_istochnika || null)
    || (Number(р.kartinok) || 0) !== (Number(з.kartinok) || 0)
    || числоИли(р.dlitelnost_s) !== числоИли(з.dlitelnost_s)
    || !!р.bez_prevyu !== !!з.bez_prevyu;
  const правки = [];
  for (const з of записи) {
    const р = есть.get(з.klyuch);
    if (!р || р.skryto || з.data < порогПравок) continue;
    const медиа = медиаИное(р, з);
    if (р.tekst_hash === з.tekst_hash && !медиа) continue;
    /* Сменился адрес картинки — старые копии снимаем, kartinka обнуляем,
       попытки тоже: шаг картинок ниже заливает новое фото. Ключи в бакете
       считаются от klyuch и не меняются, поэтому важно именно снять старое:
       пока новое не пришло, в ленте не будет картинки вовсе — это честнее,
       чем показывать прежнее фото под новым содержанием. */
    const сменаКартинки = (р.kartinka_istochnika || null) !== (з.kartinka_istochnika || null);
    правки.push(Object.assign({}, з, {
      obnovleno_at: сейчасISO,
      сброситьКартинку: сменаКартинки && !!(р.kartinka || р.kartinka_polnaya || р.kartinka_popytok),
      былаКартинка: сменаКартинки && !!(р.kartinka || р.kartinka_polnaya),
    }));
  }

  /* 4. ЗАПИСЬ В БАЗУ — до всякой сети. Раньше сборщик сначала качал картинки
        и только потом писал пачку: 05.09.2026 функция кончилась на картинках,
        и из 18 разобранных записей легли 10, а журнал и состояние не
        записались вовсе (ревью 8.8, F02). Теперь наоборот: сеть — после.

        Остаток перед записью — в лог функции. Спасти он уже ничего не может
        (пропустить запись значило бы потерять пачку целиком), но если пачка
        когда-нибудь ляжет наполовину, в логе будет видно, что заход подошёл
        к базе почти без времени, — а не молчание, как 05.09. */
  let остатокПередЗаписью = null;
  try { остатокПередЗаписью = о.остаток(); } catch (e) { остатокПередЗаписью = null; }
  if ((новые.length || правки.length) && остатокПередЗаписью != null && остатокПередЗаписью < РЕЗЕРВ_ЗАПИСИ_МС) {
    console.warn('[lenta-sbor] ' + ист.klyuch + ': запись начата с остатком ' + остатокПередЗаписью
      + ' мс (меньше резерва ' + РЕЗЕРВ_ЗАПИСИ_МС + '): новых ' + новые.length + ', правок ' + правки.length);
  }
  for (const з of новые) { з.kartinka = null; з.kartinka_polnaya = null; з.kartinka_popytok = 0; }
  if (новые.length) await х.записать(новые);
  if (правки.length) await х.обновить(правки);

  /* 5. Итог и журнал — тоже до сети: даже если функцию оборвут на картинках,
        владелец увидит честный исход захода, а не молчание. */
  const свежая = записи.reduce((м, з) => (м && м > з.data ? м : з.data), null);
  const части = [];
  if (почтальон) части.push('через почтальона (снято ' + почтальон.снято + ', ' + почтальон.возрастМин + ' мин назад)');
  if (доборСтраниц) части.push('добрано страниц ' + доборСтраниц);
  if (скрыто) части.push('скрыто ' + скрыто);
  if (воскрешено) части.push('воскрешено ' + воскрешено);
  if (правки.length) части.push('правок ' + правки.length);
  if (заСроком) части.push('за сроком ' + заСроком);
  if (всёОтфильтровано) части.push('все ' + блоков + ' записей страницы отфильтрованы');
  const отброшеноВсего = Object.values(отб).reduce((а, n) => а + (n || 0), 0);
  if (отброшеноВсего) части.push('отброшено ' + Object.entries(отб).filter(([, n]) => n).map(([k, n]) => k + ' ' + n).join(', '));
  const изменилось = новые.length || правки.length || скрыто || воскрешено;
  const запись = await итогИст((изменилось || всёОтфильтровано) ? 'ok' : 'pusto', части.length ? части.join('; ') : null, новые.length,
    { свежая, название: сырьё.название || null });

  /* 6. Сеть после базы: снять копии у записей со сменившимся фото, скачать
        недостающие картинки (свой потолок), убрать объекты скрытых записей.
        Всё, что здесь оборвётся, доделает следующий заход. */
  let объектовУдалено = 0, объектовНеУдалено = 0, безПрава = false;
  const снять = async (р) => {
    try { await удалитьОбъекты(Object.assign({ istochnik: ист.istochnik }, р), о); объектовУдалено++; return true; }
    catch (e) {
      объектовНеУдалено++;
      if (нетПрава(e)) безПрава = true;
      console.warn('[lenta-sbor] ' + р.klyuch + ': удаление объектов: ' + коротко(e && e.message || e, 200));
      return false;
    }
  };
  if (о.бакет) {
    for (const з of правки) if (з.былаКартинка) await снять(з);
  }
  const картинки = await шагКартинок(ист, о, разборщик, сейчасISO, почтальон);
  if (о.бакет) {
    /* Скрытые (модератором через /lenta/skryt или сверкой) — объекты долой.
       Ручке доступ к бакету не нужен: убираем здесь по признаку skryto.
       403 на DELETE — нет права: строка «trevoga» в журнал источника раз в
       сутки, попытки не трогаем — как только право появится, уберём. */
    const скрытые = await х.скрытыеСКартинками(ист);
    for (const р of скрытые) {
      if (await снять(р)) await х.картинка(р.klyuch, null, null, КАРТИНКА_ПОПЫТОК, сейчасISO);
    }
    if (безПрава) await тревогаБакета(о, ист.klyuch, объектовНеУдалено);
  }

  /* Сведения о картинках — в ответ и в лог функции: журнал источника уже
     написан, второй строкой его не засоряем. */
  const хвост = [];
  if (картинки.собрано) хвост.push('картинок ' + картинки.собрано);
  if (картинки.ошибок) хвост.push('картинок не вышло ' + картинки.ошибок);
  if (картинки.обрывов) хвост.push('обрывов ' + картинки.обрывов);
  if (картинки.нетВСырье) хвост.push('нет в сырье ' + картинки.нетВСырье);
  if (картинки.остановлено) хвост.push('картинки захода остановлены');
  if (объектовУдалено) хвост.push('объектов удалено ' + объектовУдалено);
  if (объектовНеУдалено) хвост.push('объектов не удалено ' + объектовНеУдалено + (безПрава ? ' (нет права)' : ''));
  if (хвост.length) запись.soobshchenie = коротко((запись.soobshchenie ? запись.soobshchenie + '; ' : '') + хвост.join('; '), 300);
  запись.kartinok_sobrano = картинки.собрано;
  return запись;
}

/* Состояние источника и строка журнала — при ЛЮБОМ исходе. Здесь же тревога:
   24 ч без удачи → строка «trevoga», не чаще раза в сутки. */
async function итог(ист, о, начало, исход, сообщение, новых, доп) {
  доп = доп || {};
  const сейчасМс = о.сейчас();
  const удача = исход === 'ok' || исход === 'pusto';
  const запись = {
    klyuch: ист.klyuch, ishod: исход, soobshchenie: сообщение ? коротко(сообщение, 300) : null, novyh: новых || 0,
    dlitelnost_ms: Math.max(0, Date.now() - начало), udacha: удача,
    /* otkuda: чем шёл заход — timer | ruchnoj, а при выручке почтальона
       pochtalon (доп.otkuda), чтобы в журнале было видно, кто довёз. */
    otkuda: доп.otkuda || о.otkuda || 'timer',
    свежая: доп.свежая || null, название: доп.название || null,
  };
  let zapisej = null;
  try { zapisej = await о.хранилище.количество(ист); } catch (e) { zapisej = null; }
  await о.хранилище.состояние(ист, Object.assign({ zapisej, сейчасISO: isoМс(сейчасМс) }, запись));
  await о.хранилище.журнал(запись);
  if (!удача && исход !== 'propusk') {
    const безУдачиМс = ист.udacha_at
      ? сейчасМс - Date.parse(ист.udacha_at)
      : ((Number(ист.oshibok_podryad) || 0) + 1) * (Number(ист.period_min) || 15) * 60000;
    if (безУдачиМс >= ТРЕВОГА_ЧАСОВ * 3600000) {
      const была = await о.хранилище.тревогаБыла(ист.klyuch, isoМс(сейчасМс - ТРЕВОГА_ЧАСОВ * 3600000));
      if (!была) {
        await о.хранилище.журнал({ klyuch: ист.klyuch, ishod: 'trevoga', novyh: 0, dlitelnost_ms: 0, otkuda: запись.otkuda,
          soobshchenie: 'нет удачного опроса ' + Math.round(безУдачиМс / 3600000) + ' ч: ' + (запись.soobshchenie || исход) });
        запись.trevoga = true;
      }
    }
  }
  return запись;
}

/* ─── уборка раз в сутки ─────────────────────────────────────────────────── */
async function уборка(о, источники) {
  const х = о.хранилище;
  const сейчасМс = о.сейчас();
  const последняя = await х.последняяУборка();
  if (последняя && сейчасМс - Date.parse(последняя) < УБОРКА_РАЗ_В_ЧАСОВ * 3600000) return null;
  const начало = Date.now();
  const порог = isoМс(сейчасМс - ХРАНИТЬ_ДНЕЙ * 86400000);
  let удалено = 0, объектов = 0, неУдалено = 0, безПрава = false;
  for (const ист of источники) {
    if (о.остаток() < МИН_ОСТАТОК_МС) break;
    const строки = (await х.всеЗаписиКанала(ист)).slice().sort(поУбыванию);
    for (let i = БЕЗ_СРОКА_ЗАПИСЕЙ; i < строки.length; i++) {
      const р = строки[i];
      if (р.data >= порог) continue;
      /* Строка без объектов не удаляется: иначе копии в бакете осиротеют. */
      if (о.бакет && (р.kartinka || р.kartinka_polnaya)) {
        try { await удалитьОбъекты(Object.assign({ istochnik: ист.istochnik }, р), о); объектов++; }
        catch (e) {
          неУдалено++;
          if (нетПрава(e)) безПрава = true;
          console.warn('[lenta-sbor] уборка ' + р.klyuch + ': ' + коротко(e && e.message || e, 200));
          continue;
        }
      }
      await х.удалить(р.klyuch);
      удалено++;
    }
  }
  if (безПрава) await тревогаБакета(о, 'uborka', неУдалено);
  const журнала = await х.убратьЖурнал(isoМс(сейчасМс - ЖУРНАЛ_ДНЕЙ * 86400000));
  const запись = { klyuch: 'uborka', ishod: 'ok', novyh: 0, dlitelnost_ms: Date.now() - начало, otkuda: о.otkuda || 'timer',
    soobshchenie: 'удалено записей ' + удалено + ', объектов ' + объектов
      + (неУдалено ? ', объектов не удалено ' + неУдалено + (безПрава ? ' (нет права)' : '') : '')
      + ', строк журнала ' + (журнала == null ? '?' : журнала) };
  await х.журнал(запись);
  return запись;
}

/* ─── весь запуск ────────────────────────────────────────────────────────── */
async function сбор(о, задание) {
  задание = задание || {};
  const х = о.хранилище;
  const все = await х.источники();
  о.своиКаналы = все.filter((и) => и.istochnik === 'telegram').map((и) => и.kanal);
  о.otkuda = задание.otkuda || 'timer';
  /* Предохранитель картинок — на весь заход, а не на источник: два обрыва
     подряд значат, что недоступен хост, и дёргать его у остальных каналов
     незачем (ревью 8.8, F03). Записи при этом собираются как обычно. */
  о.картинки = { обрывов: 0, остановлены: false };
  const т = о.сейчас();

  let очередь;
  const отчёт = [];
  if (задание.istochnik) {
    const и = все.find((x) => x.klyuch === задание.istochnik);
    if (!и) return { всего: все.length, опрошено: 0, отчёт: [], ошибка: 'нет источника ' + задание.istochnik };
    if (!и.vklyuchen) { отчёт.push({ klyuch: и.klyuch, ishod: 'propusk', soobshchenie: 'источник выключен' }); очередь = []; }
    else очередь = [и];
  } else if (задание.vse) {
    очередь = все.filter((и) => и.vklyuchen);
  } else {
    /* Просроченные. Обычный шаг — period_min (Телеграм: час). После сбоя
       ждём МЕНЬШЕ, а не больше: t.me из облака отвечает через раз, и канал,
       не ответивший в 17:03, надо спросить на следующем тике, а не через два
       часа: 15 мин × число сбоев подряд, но не дольше самого периода. */
    очередь = все.filter((и) => {
      if (!и.vklyuchen) return false;
      if (!и.proveren_at) return true;
      const период = Number(и.period_min) || 15, сбоев = Number(и.oshibok_podryad) || 0;
      const шагМин = сбоев > 0 ? Math.min(период, 15 * сбоев) : период;
      /* Допуск 3 минуты: тик приходит в :03:0x, а прошлая проверка кончилась
         в :03:4x — без допуска канал «не просрочен» на сорок секунд и ждёт
         следующего тика, и час на деле превращался в час с четвертью. */
      return Date.parse(и.proveren_at) + шагМин * 60000 - 3 * 60000 <= т;
    });
  }
  /* Телеграм первым: у него самые живые каналы; если бюджет кончится, пусть
     отстанет Rutube. Внутри — кто дольше ждал. */
  очередь.sort((a, b) => ((a.istochnik === 'telegram' ? 0 : 1) - (b.istochnik === 'telegram' ? 0 : 1))
    || (Date.parse(a.proveren_at || 0) - Date.parse(b.proveren_at || 0)));

  let первый = true;
  for (const ист of очередь) {
    if (о.остаток() < МИН_ОСТАТОК_МС) { отчёт.push({ klyuch: ист.klyuch, ishod: 'propusk', soobshchenie: 'кончился бюджет времени' }); continue; }
    if (!первый && о.пауза) await о.пауза(ПАУЗА_МЕЖДУ_КАНАЛАМИ_МС);
    первый = false;
    try { отчёт.push(await собратьИсточник(ист, о)); }
    catch (e) {
      /* Сюда попадает только сбой самого хранилища: журнал мог не записаться,
         поэтому хотя бы в лог. */
      console.error('[lenta-sbor] ' + ист.klyuch, e);
      отчёт.push({ klyuch: ист.klyuch, ishod: 'oshibka', soobshchenie: коротко(e && e.message || e) });
    }
  }

  let убрано = null;
  if (!задание.istochnik) {
    try { убрано = await уборка(о, все); }
    catch (e) { console.error('[lenta-sbor] уборка', e); убрано = { ishod: 'oshibka', soobshchenie: коротко(e && e.message || e) }; }
  }
  return { всего: все.length, опрошено: очередь.length, отчёт, уборка: убрано };
}

/* ─── событие → задание ──────────────────────────────────────────────────── */
/* Таймер: { messages: [{ event_metadata: { event_type: '…TimerMessage' },
   details: { trigger_id, payload? } }] }. Ручной invoke: тело как есть
   ({"istochnik":"telegram:astronevod"} или {"vse":true}). HTTP-вызов (если
   маршрут будет заведён): тело запроса. */
function разобратьСобытие(event) {
  const з = { otkuda: 'ruchnoj' };
  let тело = null;
  if (event && Array.isArray(event.messages)) {
    з.otkuda = 'timer';
    const д = event.messages[0] && event.messages[0].details;
    if (д && typeof д.payload === 'string' && д.payload.trim()) { try { тело = JSON.parse(д.payload); } catch (e) { тело = null; } }
  } else if (event && event.httpMethod) {
    if (event.httpMethod === 'POST' && event.body) {
      try { тело = JSON.parse(event.isBase64Encoded ? Buffer.from(event.body, 'base64').toString('utf8') : event.body); } catch (e) { return { ошибка: 'тело не JSON' }; }
    }
  } else if (event && typeof event === 'object') {
    тело = event;
  }
  if (тело && typeof тело === 'object') {
    if (тело.vse === true) з.vse = true;
    if (тело.istochnik != null) {
      const и = String(тело.istochnik).trim();
      if (!/^[a-z]+:[A-Za-z0-9_+\-]{1,80}$/.test(и)) return { ошибка: 'плохой istochnik' };
      з.istochnik = и;
    }
  }
  return з;
}

/* ─── вход функции ───────────────────────────────────────────────────────── */
exports.handler = async function handler(event, context) {
  const задание = разобратьСобытие(event);
  if (задание.ошибка) return { statusCode: 400, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ error: задание.ошибка }) };
  const о = await exports.окружениеОблака(context);
  const р = await сбор(о, задание);
  console.log('[lenta-sbor] ' + JSON.stringify(р));
  return { statusCode: 200, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(р) };
};

