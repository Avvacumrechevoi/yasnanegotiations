/* ═══════════════════════════════════════════════════════════════════════════
   ЦИТАТА ДНЯ — и её утреннее напоминание.

   Один файл на два экрана: главная показывает цитату, Профиль включает и
   выключает утреннее уведомление с ней. Список ОБЩИЙ нарочно: если бы
   каждый экран держал свой, тексты разошлись бы на первой же правке.

   ВСЕ ЦИТАТЫ — ДОСЛОВНЫЕ СТРОКИ ИЗ КНИГИ «ЯСНА СУТОК», выверенные по
   корпусу в работе над интерактивом лендинга (номера пунктов — авторская
   нумерация разбора). Ничего не сочинено и не «улучшено»: цитата, которую
   подкрутили, перестаёт быть цитатой.

   Ротация — по дню года: у всех пользователей в один день одна цитата,
   и уведомление совпадает с тем, что человек увидит на главной.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  window.YASNA_CITATY = [
    /* [цитата, о чём она, № пункта] */
    ['Самое холодное время суток есть первое время, время Первый Свет.',
      'о времени Искры', '№439'],
    ['Кончилась тьма ночи, и начинается время утренней зари.',
      'о первом свете', '№87.4'],
    ['Появляется краешек солнечного круга.',
      'о выходе солнца', '№87.6'],
    ['Диск солнца проходит линию горизонта всего за две минуты.',
      'о восходе и заходе', '№199'],
    ['Перестала расти общая освещённость. Начался светлый день.',
      'о начале дня', '№87.8'],
    ['Самое тёплое время суток — седьмое время. Первая Тьма.',
      'о том, когда жарче всего', '№438'],
    ['Все долгие времена сутки есть времена медленных изменений общей обстановки.',
      'о долгих временах', '№95'],
    ['Во всех долгих временах обстановка изменяется плавно, постепенно.',
      'о ходе суток', '№101'],
    ['Здесь кончается самый последний свет солнца и начинается время тьмы ночи.',
      'о конце сумерек', '№87.2'],
    ['В моменты Солнцестояний точка выхода стоит на одном месте 3 дня.',
      'о круге года', '№230–235'],
    ['И здесь день равен ночи.',
      'о равноденствии', '№230–235'],
    ['Это звонок будильника. Пора вставать.',
      'о колокольчиках первого света', '№896'],
  ];

  function деньГода(дата) {
    return Math.floor((дата - new Date(дата.getFullYear(), 0, 0)) / 864e5);
  }

  /* Цитата на данную дату. */
  window.yasnaCitata = function (дата) {
    var д = дата || new Date();
    return window.YASNA_CITATY[деньГода(д) % window.YASNA_CITATY.length];
  };

  /* ── Утреннее уведомление ────────────────────────────────────────────────
     Родные местные уведомления Android: без сервера, работают офлайн.
     Расписываем на две недели вперёд, каждое — с цитатой своего дня;
     при каждом открытии приложения расписание сдвигается заново, так что
     запас не кончается. Выключение снимает всё расписание.

     Час выбран утренний (9:30): цитаты — из книги про сутки, и утро им
     к лицу; точная минута не важна, и точных будильников (отдельное
     разрешение Android) мы не просим. */
  var ЧАС = 9, МИНУТА = 30, ДНЕЙ = 14, БАЗА_ID = 7100;
  var КЛЮЧ = 'yasna_citata_push';           /* '1' — включено владельцем */

  function плагин() {
    var C = window.Capacitor;
    return (C && C.Plugins && C.Plugins.LocalNotifications) || null;
  }

  window.yasnaPushiVkl = function () {
    try { return localStorage.getItem(КЛЮЧ) === '1'; } catch (e) { return false; }
  };

  /* Включить/обновить или выключить. Возвращает Promise<'granted'|'denied'|
     'unavailable'>. Вызывается из Профиля (по тумблеру) и с главной
     (молчаливое обновление расписания, если уже включено). */
  window.yasnaPushi = function (вкл) {
    var LN = плагин();
    if (!LN) return Promise.resolve('unavailable');

    var снять = { notifications: [] };
    for (var i = 0; i < ДНЕЙ; i++) снять.notifications.push({ id: БАЗА_ID + i });

    if (!вкл) {
      try { localStorage.setItem(КЛЮЧ, '0'); } catch (e) {}
      return LN.cancel(снять).then(function () { return 'granted'; },
                                   function () { return 'granted'; });
    }

    return LN.requestPermissions().then(function (р) {
      if (!р || р.display !== 'granted') return 'denied';
      try { localStorage.setItem(КЛЮЧ, '1'); } catch (e) {}
      return LN.cancel(снять).catch(function () {}).then(function () {
        var список = [];
        var сейчас = new Date();
        for (var i = 0; i < ДНЕЙ; i++) {
          var когда = new Date(сейчас.getFullYear(), сейчас.getMonth(),
                               сейчас.getDate() + i, ЧАС, МИНУТА, 0);
          if (когда <= сейчас) continue;      /* сегодняшнее утро уже прошло */
          var ц = window.yasnaCitata(когда);
          список.push({
            id: БАЗА_ID + i,
            title: 'Ясна · цитата дня',
            body: '«' + ц[0] + '» — ' + ц[1],
            /* НЕТОЧНЫЙ будильник — принципиально. Точный (умолчание плагина)
               на Android 12+ требует особого доступа «Будильники и
               напоминания», и schedule() уводит человека в системные
               настройки прямо с кнопки «Включить» — проверено на устройстве.
               Утренней цитате точность до минуты не нужна. */
            schedule: { at: когда },
            isExactNotification: false,
            smallIcon: 'ic_launcher_foreground'
          });
        }
        return LN.schedule({ notifications: список }).then(function () { return 'granted'; });
      });
    }).catch(function () { return 'denied'; });
  };
})();
