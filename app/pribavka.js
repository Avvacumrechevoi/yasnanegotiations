/* ═══════════════════════════════════════════════════════════════════════════
   ПРИБАВКА ПРИЛОЖЕНИЯ. Кладётся только в www/, на сайт не едет.

   Три вещи, без которых обёртка остаётся сайтом в рамке — и по которым это
   видно и человеку, и тому, кто проверяет приложение в магазине. И Google
   Play, и RuStore отдельно оговаривают: обёртка, просто показывающая сайт,
   отклоняется.

   1. КНОПКА «НАЗАД». Самый заметный признак. На телефоне она системная, и
      если приложение на неё не отвечает — оно закрывается посреди урока.
      Здесь: есть куда вернуться — возвращаемся; некуда — сворачиваемся, а не
      закрываемся, как ведёт себя любое приложение с главного экрана.
   2. СТРОКА СОСТОЯНИЯ. Цвет тот же, что у знака и у сайта. Без этого сверху
      висит чужая полоса.
   3. ЗНАК О ПРОПАЖЕ СЕТИ. Содержимое лежит внутри приложения и работает без
      сети, а вот прогресс, рейтинг и спарринг — нет. Человек должен понимать,
      почему кнопка не отвечает, а не думать, что сломалось приложение. Знак
      показывается ненадолго и уходит сам: постоянная полоса внизу перекрывала
      собственные кнопки страниц.

   Плагины берём через window.Capacitor.Plugins — мост подкладывает их сам,
   сборщик для этого не нужен.
   ═══════════════════════════════════════════════════════════════════════════ */
(function () {
  var C = window.Capacitor;
  if (!C || !C.Plugins) return;                 /* открыли в браузере — молчим */
  var P = C.Plugins;

  /* ── 1. Кнопка «назад» ─────────────────────────────────────────────────── */
  if (P.App && P.App.addListener) {
    P.App.addListener('backButton', function (e) {
      /* Сначала спрашиваем страницу: вдруг открыт попап или слой, и «назад»
         должен закрыть его, а не уводить с экрана. Страница отвечает тем, что
         отменяет событие. */
      var своё = new CustomEvent('yasna:назад', { cancelable: true });
      var перехватили = !window.dispatchEvent(своё);
      if (перехватили) return;

      if (e && e.canGoBack) { window.history.back(); return; }

      /* Идти некуда. Закрывать приложение молча нельзя — человек теряет
         состояние; сворачиваем, как делает почта или браузер. */
      if (P.App.minimizeApp) P.App.minimizeApp();
    });
  }

  /* ── 2. Строка состояния и системные отступы ──────────────────────────────
     Android 15+ рисует страницу ПОД строкой состояния (edge-to-edge обязателен
     для цели 35+), и setBackgroundColor там уже не действует. Из-за этого на
     живом телефоне шапка сайта уезжала под часы — на эмулятоre без выреза
     этого не было видно. Capacitor подкладывает размеры панелей переменными
     --safe-area-inset-*; здесь мы:
       — рисуем свою синюю подложку под строкой состояния,
       — сдвигаем документ на её высоту,
       — прилипающим шапкам сайта (.ynav--sticky) даём top той же высоты,
         иначе при прокрутке они прилипали бы к краю окна и резались подложкой. */
  if (P.StatusBar) {
    try {
      /* DARK = светлые значки (стиль «на тёмном фоне») — у нас фон синий.
         Раньше стояло LIGHT, и значки были тёмными на синем. */
      P.StatusBar.setStyle({ style: 'DARK' });
      P.StatusBar.setBackgroundColor({ color: '#0071e3' }); /* Android ≤14 */
    } catch (e) {}
  }
  (function () {
    var st = document.createElement('style');
    st.textContent =
      ':root{--yasna-sverhu:var(--safe-area-inset-top, env(safe-area-inset-top, 0px));' +
      '--yasna-snizu:var(--safe-area-inset-bottom, env(safe-area-inset-bottom, 0px))}' +
      'body{padding-top:var(--yasna-sverhu) !important}' +
      '.ynav--sticky{top:var(--yasna-sverhu) !important}' +
      '#yasna-plashka{position:fixed;top:0;left:0;right:0;height:var(--yasna-sverhu);' +
      'background:#0071e3;z-index:2147483000;pointer-events:none}';
    (document.head || document.documentElement).appendChild(st);
    var pl = document.createElement('div');
    pl.id = 'yasna-plashka';
    pl.setAttribute('aria-hidden', 'true');
    (document.body || document.documentElement).appendChild(pl);
  })();

  /* ── 3. Знак о пропаже сети ────────────────────────────────────────────
     РОДНОЕ УВЕДОМЛЕНИЕ ANDROID, а не своя полоса в разметке. Две попытки до
     этого провалились на живом устройстве, и обе — по одной причине: что бы
     я ни рисовал внизу экрана, оно перекрывало собственные кнопки страниц.
     У Конструктора нижняя панель «Суток / Года / Жизни» стоит position:fixed,
     и отступом её не подвинуть. Родное уведомление всплывает поверх всего,
     живёт две секунды и ничего не держит.

     Показываем ТОЛЬКО на переходе «была сеть → не стало». Эмулятор дёргает
     событие сети каждые три секунды, и на «показывать при каждом событии»
     уведомление сыпалось бы без конца; на живом телефоне так же ведёт себя
     плохая связь. */
  var былаСеть = null;

  function проСеть(есть) {
    if (былаСеть === есть) return;          /* состояние не изменилось */
    var первыйРаз = былаСеть === null;
    былаСеть = есть;
    if (есть) return;                        /* сеть появилась — молчим */
    if (!P.Toast) return;
    P.Toast.show({
      text: первыйРаз
        ? 'Нет сети. Уроки и круг работают, прогресс сохранится позже.'
        : 'Сеть пропала. Прогресс сохранится, когда вернётся.',
      duration: 'long',
      position: 'bottom'
    }).catch(function () {});
  }

  if (P.Network) {
    P.Network.getStatus().then(function (s) { проСеть(s.connected); }).catch(function () {});
    P.Network.addListener('networkStatusChange', function (s) { проСеть(s.connected); });
  }
})();
