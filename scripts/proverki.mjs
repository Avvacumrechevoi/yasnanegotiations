/* ─── Что человек видит глазами ────────────────────────────────────────────
   Куски собираем со СМЕЩЕНИЕМ в файле, а номер строки считаем в самом конце
   по таблице переносов. Считать строки по ходу разбора я уже пробовал: одна
   пропущенная косая (деление, принятое за регулярку) — и весь остаток файла
   съезжает на сотню строк, а в журнале стоит номер, по которому ничего нет. */

/* Строковые литералы и текст JSX внутри кода. Комментарии, имена и выражения
   пропускаем. */
function кускиКода(код, сдвиг = 0) {
  const куски = [];
  const n = код.length;
  let i = 0, предыдущий = '';
  const добавить = (текст, от) => { if (текст.trim()) куски.push({ от: сдвиг + от, текст }); };

  while (i < n) {
    const c = код[i];

    if (c === '/' && код[i + 1] === '/') { while (i < n && код[i] !== '\n') i++; continue; }
    if (c === '/' && код[i + 1] === '*') {
      const конец = код.indexOf('*/', i + 2);
      i = конец < 0 ? n : конец + 2; continue;
    }

    if (c === '"' || c === "'" || c === '`') {
      const кавычка = c, начало = i;
      let буфер = '';
      i++;
      while (i < n) {
        const d = код[i];
        if (d === '\\') { i += 2; continue; }
        if (d === кавычка) { i++; break; }
        /* ${…} в шаблоне — это код, а не текст. */
        if (кавычка === '`' && d === '$' && код[i + 1] === '{') {
          let глубина = 1; i += 2;
          while (i < n && глубина > 0) {
            if (код[i] === '{') глубина++;
            else if (код[i] === '}') глубина--;
            i++;
          }
          continue;
        }
        буфер += d; i++;
      }
      добавить(буфер, начало);
      предыдущий = кавычка; continue;
    }

    /* Регулярка: её содержимое — не текст, а кавычка внутри сбила бы разбор.
       Если до конца строки закрывающей косой нет — это было деление, и
       трогать ничего нельзя. */
    if (c === '/' && /[(,=:[!&|?{};+\-*%~^<>]/.test(предыдущий)) {
      let j = i + 1;
      while (j < n && код[j] !== '/' && код[j] !== '\n') { if (код[j] === '\\') j++; j++; }
      if (код[j] === '/') { i = j + 1; предыдущий = '/'; continue; }
    }

    /* ТЕКСТ ВНУТРИ JSX. Половина видимых надписей написана детьми тегов
       (`<div>Гидов в приложении пока нет</div>`), а не строкой в кавычках:
       без этого куска правила не видели бы главного. Берём осторожно —
       только то, что читается как речь: есть кириллица и нет ничего от кода.
       Иначе сравнение `если(а > б && в < г)` попало бы в текст вместе с
       именами переменных. */
    if (c === '>') {
      const конец = код.indexOf('<', i + 1);
      if (конец > i) {
        const без = код.slice(i + 1, конец).replace(/\{[^{}]*\}/g, ' ');
        if (/[А-Яа-яЁё]/.test(без) && !/[={}();&|"'`\\]/.test(без)) добавить(без, i + 1);
      }
    }

    if (!/\s/.test(c)) предыдущий = c;
    i++;
  }
  return куски;
}

/* Текст между тегами, видимые атрибуты и содержимое <script> как кода. */
function кускиРазметки(код) {
  const куски = [];
  const n = код.length;
  let i = 0, текст = '', началоТекста = 0;
  const слить = () => {
    if (текст.trim()) куски.push({ от: началоТекста, текст });
    текст = '';
  };

  while (i < n) {
    if (код[i] !== '<') {
      if (!текст) началоТекста = i;
      текст += код[i]; i++; continue;
    }
    слить();

    if (код.startsWith('<!--', i)) {
      const конец = код.indexOf('-->', i);
      i = конец < 0 ? n : конец + 3; continue;
    }
    const тег = /^<\/?([a-zA-Z0-9-]+)((?:"[^"]*"|'[^']*'|[^>])*)>/.exec(код.slice(i));
    if (!тег) { i++; continue; }
    const имя = тег[1].toLowerCase(), атрибуты = тег[2] || '';
    /* Видимые атрибуты: их показывают подсказкой и читают вслух. */
    for (const м of атрибуты.matchAll(/\b(title|alt|placeholder|aria-label)\s*=\s*(["'])([^"']*)\2/gi))
      if (м[3].trim()) куски.push({ от: i + м.index, текст: м[3] });
    i += тег[0].length;

    if (имя === 'script' || имя === 'style') {
      const закрыт = new RegExp('</' + имя + '\\s*>', 'i').exec(код.slice(i));
      const конецТела = закрыт ? i + закрыт.index : n;
      if (имя === 'script') for (const к of кускиКода(код.slice(i, конецТела), i)) куски.push(к);
      i = закрыт ? конецТела + закрыт[0].length : n;
    }
  }
  слить();
  return куски;
}

/* Смещение → номер строки. Одна таблица на файл. */
function построчно(код, куски) {
  const переносы = [];
  for (let i = 0; i < код.length; i++) if (код[i] === '\n') переносы.push(i);
  const строкаПо = (от) => {
    let л = 0, п = переносы.length;
    while (л < п) { const с = (л + п) >> 1; if (переносы[с] < от) л = с + 1; else п = с; }
    return л + 1;
  };
  return куски.map((к) => ({ строка: строкаПо(к.от), текст: к.текст }));
}

export function видимыеКуски(имяФайла, код) {
  const сырые = /\.html?$/i.test(имяФайла) ? кускиРазметки(код) : кускиКода(код);
  return построчно(код, сырые);
}

/* ─── Обход исходников ───────────────────────────────────────────────────── */

export function собратьИсходники(корень) {
  const найдено = [];
  const обойти = (dir) => {
    for (const имя of readdirSync(dir)) {
      if (имя.startsWith('.')) continue;
      const путь = join(dir, имя);
      const отн = relative(корень, путь).split(sep).join('/');
      if (НЕ_СМОТРЕТЬ.some((x) => отн === x.replace(/\/$/, '') || отн.startsWith(x))) continue;
      if (statSync(путь).isDirectory()) { обойти(путь); continue; }
      if (/\.(html|js)$/i.test(имя)) найдено.push({ путь, отн });
    }
  };
  обойти(корень);
  return найдено;
}

/* ─── Правила по словам ──────────────────────────────────────────────────── */

export function проверитьТексты(файлы) {
  const находки = [];
  for (const { путь, отн } of файлы) {
    const код = readFileSync(путь, 'utf8');
    let куски = null;
    for (const правило of ПРАВИЛА) {
      if (правило.где === 'оболочка' && материал(отн)) continue;
      if (!куски) куски = видимыеКуски(отн, код);
      for (const к of куски) {
        for (const слово of правило.найти(к.текст)) {
          находки.push({
            правило: правило.имя, заголовок: правило.заголовок,
            файл: отн, строка: к.строка, слово,
            кусок: к.текст.trim().replace(/\s+/g, ' ').slice(0, 90),
          });
        }
      }
    }
  }
  /* Ключи хранилища проверяем здесь же, чтобы обе сборки получили правило
     без единой правки в себе: проверитьТексты они уже зовут. */
  return находки.concat(проверитьКлючи(файлы));
}

/* ─── Правило по ключам хранилища ────────────────────────────────────────
   ЗАЧЕМ. Реестр в docs/core/storage.js заведён затем, чтобы прогресс нельзя
   было потерять: только по нему собирается снапшот и только он уезжает в
   PUT /progress. Но реестр — обычный объект, и мимо него написать
   localStorage.setItem('yasna_что_то', …) ничего не мешало. Так и вышло:
   прогресс чтения книг, круг и список друзей писались годными ключами, в
   реестр не попали и никуда не уезжали — обещание «вернётся после
   переустановки» для них было ложью. Глазами это не ловится: ключ
   появляется в одной строке посреди чужого файла.

   ЧТО СЧИТАЕМ. Литерал вида yasna_… в видимом коде (комментарии разбор уже
   выкинул). Литерал засчитывается, если он есть в KEYS, начинается с
   зарегистрированного префикса или сам является таким префиксом без
   хвостового разделителя ('yasna_ekran_v1' при префиксе 'yasna_ekran_v1:').

   ГДЕ РЕЕСТР. Всегда docs/core/storage.js рядом с этим файлом: у сборки
   витрины своего реестра нет, а правда должна быть одна. */
const РЕЕСТР_ПУТЬ = join(fileURLToPath(new URL('.', import.meta.url)), '..', 'docs', 'core', 'storage.js');

function читатьРеестр(путь) {
  if (!existsSync(путь)) return null;
  const код = readFileSync(путь, 'utf8');
  const кусок = (от, до) => {
    const н = код.indexOf(от);
    if (н < 0) return '';
    const к = код.indexOf(до, н);
    return к < 0 ? '' : код.slice(н, к);
  };
  const ключи = new Set();
  for (const м of кусок('var KEYS = {', '\n  };').matchAll(/(?:^|\n)\s*(yasna[A-Za-z0-9_]*)\s*:/g))
    ключи.add(м[1]);
  const префиксы = [];
  for (const м of кусок('var PREFIXES = [', '\n  ];').matchAll(/prefix:\s*'([^']+)'/g))
    префиксы.push(м[1]);
  return ключи.size ? { ключи, префиксы } : null;
}

let реестр;   /* читаем один раз на процесс: сборок две, файл один */

export function проверитьКлючи(файлы, путьРеестра = РЕЕСТР_ПУТЬ) {
  if (реестр === undefined) реестр = читатьРеестр(путьРеестра);
  if (!реестр) {
    return [{ правило: 'ключи',
              заголовок: 'РЕЕСТРА КЛЮЧЕЙ НЕ ВИДНО — без него нечем проверить, что прогресс не потеряется',
              файл: relative(process.cwd(), путьРеестра).split(sep).join('/'), строка: 0, слово: '',
              кусок: 'ожидался объект KEYS в docs/core/storage.js' }];
  }
  /* Префикс без хвостового разделителя: 'yasna_ekran_v1:' → 'yasna_ekran_v1'.
     Сам разделитель в литерал ключа входит, а в найденное слово — нет. */
  const голые = реестр.префиксы.map((п) => п.replace(/[^A-Za-z0-9_]+$/, ''));
  const свой = (имя) =>
    реестр.ключи.has(имя) ||
    реестр.префиксы.some((п) => имя.startsWith(п)) ||
    голые.includes(имя);

  const находки = [];
  for (const { путь, отн } of файлы) {
    const код = readFileSync(путь, 'utf8');
    for (const к of видимыеКуски(отн, код)) {
      /* Граница слева обязательна: '__yasna_probe' — не ключ прогресса, а
         пробник доступности хранилища внутри самого storage.js. */
      for (const м of к.текст.matchAll(/(?<![A-Za-z0-9_])yasna[0-9]*_[A-Za-z0-9_]*/g)) {
        if (свой(м[0])) continue;
        находки.push({
          правило: 'ключи',
          заголовок: 'КЛЮЧ ХРАНИЛИЩА МИМО РЕЕСТРА — что не в KEYS, то не попадёт ни в снапшот, ни на сервер',
          файл: отн, строка: к.строка, слово: м[0],
          кусок: 'впишите ключ в KEYS (или PREFIXES) в docs/core/storage.js со своим scope',
        });
      }
    }
  }
  return находки;
}

/* ─── Правила по дереву знаний ───────────────────────────────────────────
   Дерево — обычный скрипт, объявляющий window.YasnaDerevo. Выполняем его в
   песочнице (так же, как build.mjs читает уроки) и смотрим на узлы, а не на
   текст: дубль id в пятистах строках глазами не находится. */
export function проверитьДерево(путь, отн = 'core/derevo-dannye.js') {
  /* Пропажу дерева тоже говорим словами, а не стеком ENOENT: без него
     экран «Уроки» пуст, и молчать об этом нельзя. */
  if (!existsSync(путь))
    return [{ правило: 'дерево', заголовок: 'ДЕРЕВА ЗНАНИЙ НЕТ НА МЕСТЕ',
              файл: отн, строка: 0, слово: '', кусок: путь }];
  const код = readFileSync(путь, 'utf8');
  const песок = { window: {} };
  vm.createContext(песок);
  try { vm.runInContext(код, песок, { timeout: 5000 }); }
  catch (e) {
    return [{ правило: 'дерево', заголовок: 'ДЕРЕВО ЗНАНИЙ НЕ ВЫПОЛНИЛОСЬ',
              файл: отн, строка: 0, слово: '', кусок: e.message.slice(0, 120) }];
  }
  const Д = песок.window.YasnaDerevo;
  if (!Д || !Array.isArray(Д.ВЕТВИ)) {
    return [{ правило: 'дерево', заголовок: 'ДЕРЕВО ЗНАНИЙ НЕ ОБЪЯВИЛО ВЕТВИ',
              файл: отн, строка: 0, слово: '', кусок: 'window.YasnaDerevo.ВЕТВИ' }];
  }

  /* Строку узла ищем по его id в исходнике — иначе в журнале негде смотреть. */
  const строки = код.split('\n');
  const строкаId = (id) => {
    const re = new RegExp("id:\\s*['\"]" + id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + "['\"]");
    const все = [];
    строки.forEach((с, i) => { if (re.test(с)) все.push(i + 1); });
    return все;
  };

  const находки = [];
  const скажи = (заголовок, id, кусок, строка) =>
    находки.push({ правило: 'дерево', заголовок, файл: отн, строка: строка || (строкаId(id)[0] || 0), слово: id, кусок });

  const встречен = new Map();
  for (const в of Д.ВЕТВИ) {
    for (const у of (в.узлы || [])) {
      const прежняя = встречен.get(у.id);
      if (прежняя) {
        /* УНИКАЛЬНОСТЬ id. Узел ищут по id (YasnaDerevo.узел), и дубль решает
           спор молча: так книга «Ясна Суток» открывала экран Игр. */
        скажи('ДУБЛЬ id В ДЕРЕВЕ — поиск по id отдаст один узел, а человек нажмёт на другой',
              у.id, `«${прежняя.имя}» (ветвь ${прежняя.ветвь}) и «${у.имя}» (ветвь ${в.id})`,
              строкаId(у.id)[1] || 0);
      } else встречен.set(у.id, { имя: у.имя, ветвь: в.id });

      /* КНИГА ВЕДЁТ В КНИГУ. Жанр — обещание, данное подписью на карточке:
         «книга · читать». Любой другой адрес превращает подпись в обман. */
      if (у.жанр === 'книга' && у.адрес && !/^kniga\.html(\?|#|$)/.test(у.адрес))
        скажи('КНИГА ВЕДЁТ НЕ В КНИГУ — жанр «книга» открывается только kniga.html',
              у.id, `«${у.имя}» → ${у.адрес}`);

      /* «нет: true» И РАБОЧИЙ АДРЕС ОДНОВРЕМЕННО. Карточка пишет «в
         приложении пока нет» и при этом никуда не ведёт по нажатию — или
         ведёт, и тогда надпись врёт. Одно из двух лишнее. */
      if (у.нет && у.адрес)
        скажи('«В ПРИЛОЖЕНИИ ПОКА НЕТ» ПРИ РАБОЧЕМ АДРЕСЕ — надпись и ссылка говорят разное',
              у.id, `«${у.имя}» → ${у.адрес}`);
    }
  }
  return находки;
}

/* ─── Правила по нативному мосту ─────────────────────────────────────────
   Числа из JS доходят до плагина через JSON, и мост кладёт их в org.json как
   Integer. PluginCall.getLong отдаёт значение, ТОЛЬКО если оно уже Long, а
   иначе молча возвращает запасное — ошибки не будет, будет ноль. Ровно так
   размер обновления приходил нулём, и канал обновлений молчал четыре версии
   подряд: приложение отказывалось качать исправный файл, ссылаясь на
   отсутствующий отпечаток. Ошибка тихая, глазами в ревью не видна и в
   журнале сборки ничем себя не выдаёт — поэтому она живёт здесь.

   Правильный способ один: call.getData().optLong(…) / optInt(…) / optDouble(…)
   — они из org.json и приводят к числу любой из видов, что бы мост ни
   положил. Для строк call.getString безопасен: строка приходит строкой. */
const МОСТ_ЗАПРЕТ = /\bcall\s*\.\s*(getLong|getInt|getFloat|getDouble)\s*\(/g;

export function проверитьМост(корень, отн = 'app/android') {
  if (!existsSync(корень)) return [];
  const находки = [];
  const обойти = (папка) => {
    for (const имя of readdirSync(папка)) {
      const путь = join(папка, имя);
      const с = statSync(путь);
      if (с.isDirectory()) { обойти(путь); continue; }
      if (!имя.endsWith('.java') && !имя.endsWith('.kt')) continue;
      const код = readFileSync(путь, 'utf8');
      const строки = код.split('\n');
      строки.forEach((строка, i) => {
        МОСТ_ЗАПРЕТ.lastIndex = 0;
        let м;
        while ((м = МОСТ_ЗАПРЕТ.exec(строка))) {
          const верно = м[1].replace('get', 'opt');
          находки.push({
            правило: 'мост',
            заголовок: 'ЧИСЛО С МОСТА ЧЕРЕЗ call.getLong/getInt — вернёт запасное значение, а не число',
            файл: join(отн, relative(корень, путь)).split(sep).join('/'),
            строка: i + 1,
            слово: м[1],
            кусок: `замените на call.getData().${верно}(…)`,
          });
        }
      });
    }
  };
  обойти(корень);
  return находки;
}

/* ─── Печать ─────────────────────────────────────────────────────────────
   Один вид у обеих сборок: заголовок правила, потом места. */
export function напечатать(находки, где) {
  if (!находки.length) {
    console.log(`  словарь, обещания и дерево проверены (${где}) — чисто`);
    return false;
  }
  const поЗаголовку = new Map();
  for (const н of находки) {
    if (!поЗаголовку.has(н.заголовок)) поЗаголовку.set(н.заголовок, []);
    поЗаголовку.get(н.заголовок).push(н);
  }
  for (const [заголовок, список] of поЗаголовку) {
    console.log(`\n  ⚠ ${заголовок}:`);
    for (const н of список.slice(0, 60))
      console.log(`    ${н.файл}:${н.строка} — «${н.слово}» · ${н.кусок}`);
    if (список.length > 60) console.log(`    · … и ещё ${список.length - 60}`);
  }
  console.log(`\n  всего мест: ${находки.length} (${где}). Сборка помечена неудачной: слово на экране —`);
  console.log('  часть продукта, а не мелочь. Правится текст, а не правило.');
  return true;
}
